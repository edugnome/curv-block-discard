def _merge(*groups: dict[str, str]) -> dict[str, str]:
    """Union of the group dicts; ``ValueError`` naming the key on the first overlap.

    Every manuscript macro is owned by exactly one of Stage A, Stage B or the
    validity trajectory (`_stage_a`, `_stage_b`, `_validity`): a name produced by two
    of them is a bug in this module, not a legitimate alias, so `num_b` refuses to
    pick one silently.
    """
    merged: dict[str, str] = {}
    for group in groups:
        for key, value in group.items():
            if key in merged:
                raise ValueError(f"duplicate macro name: {key}")
            merged[key] = value
    return merged


def _group_sizes(
    bundle: dict[str, Any],
    experiment: str,
    model_key: str,
    seed_payloads: Iterable[dict[str, Any]],
) -> list[int] | None:
    """A ``group_sizes`` already recorded on any of ``seed_payloads``, or the
    architecture rebuilt on CPU (`experiments.group_sizes.group_sizes_for`) when none
    of them carries one yet. Mirrors `paper_data.tables.exp789._phi_null_cell`'s
    fallback for tab:phi-map's own Phi_null column; that helper is private to the
    table module, so the two-step lookup is repeated here rather than imported.
    """
    for payload in seed_payloads:
        sizes = payload.get("group_sizes")
        if sizes is not None:
            return list(sizes)
    num_classes = bundle.get("meta", {}).get("config", {}).get("num_classes")
    return group_sizes_for(experiment, model_key, num_classes)


def _mean_phi_sep(seed_payloads: Iterable[dict[str, Any]]) -> float:
    """Mean over seeds of `hessian.phi_sep` on each seed's own diagonal block norms.

    ``diag_frob`` contains the plain norms ``||H_vv||_F``, not their squares;
    this is the same reference computed for a tab:phi-map cell.
    """
    values = [phi_sep(p["diag_frob"]) for p in seed_payloads]
    return sum(values) / len(values)


def _phi_by_probes(payload: dict[str, Any], probes: str) -> float:
    """The Phi estimate at ``probes`` Hutchinson probes, falling back to the headline
    ``phi`` when the sweep, or that probe count in it, is absent.

    The long-schedule trap: `paper_data.analysis._phi_estimate` and
    `paper_data.tables.exp789._phi_at` make exactly this choice already, both private
    to their own module, so it is repeated here on the two fields every bundle
    carries rather than imported.
    """
    by_probes = payload.get("phi_by_probes")
    if by_probes and probes in by_probes:
        return float(by_probes[probes])
    return float(payload["phi"])


def _gran_diag_frob(payload: dict[str, Any], level: str) -> dict[str, float]:
    """One seed's diagonal block norms at ``level`` (one of `experiments.regroup.
    LEVELS`): the bundle's own top-level ``diag_frob`` for "stage", ``diag_frob_
    by_granularity[level]`` otherwise -- the two fields `runner_exp8._measure_
    checkpoint` writes, "stage" being `Regrouped`'s name for the model's unmodified
    partition, which is therefore never re-measured under that key."""
    if level == "stage":
        return payload["diag_frob"]
    return payload["diag_frob_by_granularity"][level]


def _gran_phi(payload: dict[str, Any], level: str) -> float:
    """One seed's Phi at ``level``, the same "stage"-is-the-headline-field
    convention as `_gran_diag_frob`."""
    if level == "stage":
        return float(payload["phi"])
    return float(payload["phi_by_granularity"][level])


def _sum_and_sumsq(
    block_norms: Sequence[float] | Mapping[str, float],
) -> tuple[float, float]:
    """(sum_v a_v, sum_v a_v^2) for the plain diagonal block norms `phi_sep`/`n_eff`
    take -- the pair of sums both `_s_value` and `_off_over_sep` build on. Mirrors
    `hessian.phi_baselines._as_values`'s mapping-or-sequence convention, private to
    that module, so repeated here rather than imported."""
    values = (
        list(block_norms.values())
        if isinstance(block_norms, Mapping)
        else list(block_norms)
    )
    total = float(sum(values))
    sumsq = float(sum(v * v for v in values))
    return total, sumsq


def _s_value(block_norms: Sequence[float] | Mapping[str, float], phi: float) -> float:
    r"""S = (sum_v a_v)^2 (1 - Phi) / sum_v a_v^2: the whole off-block content of Phi. S = 1 exactly when the off-block squared mass equals a
    separable profile's value, sum_{v!=w} a_v a_w; S > 1 is below that value, S < 1
    above it. Defined once and used everywhere S appears (SGran*, OffOverSepGran*,
    and the two identity tests of test_paper_data_numbers.py).
    """
    total, sumsq = _sum_and_sumsq(block_norms)
    return total**2 * (1.0 - phi) / sumsq


def _off_over_sep(
    block_norms: Sequence[float] | Mapping[str, float], phi: float
) -> float:
    r"""(||H||_F^2 - sum_v a_v^2) / ((sum_v a_v)^2 - sum_v a_v^2): the off-block
    squared mass over the value a separable profile would give it, with
    ||H||_F^2 = sum_v a_v^2 / (1 - Phi) (the same diagonal-mass identity used
    elsewhere in this module). Equal to Phi / (S * Phi_sep) in closed form.
    """
    total, sumsq = _sum_and_sumsq(block_norms)
    h_frob2 = sumsq / (1.0 - phi)
    return (h_frob2 - sumsq) / (total**2 - sumsq)


def _granularity_stats(
    seed_payloads: Sequence[dict[str, Any]], level: str
) -> dict[str, float]:
    """The group count, and the seed-mean Phi/Phi_sep/S/off-over-sep, at one
    granularity ``level``, over ``seed_payloads`` -- one consistent measurement per
    level. Each mean is of the
    per-seed statistic, not a statistic of the per-seed means (`_mean_phi_sep`'s own
    convention); rounding happens once, in `_stage_a`, on each mean this returns.
    """
    a = [_gran_diag_frob(p, level) for p in seed_payloads]
    phi = [_gran_phi(p, level) for p in seed_payloads]
    pairs = list(zip(a, phi, strict=True))
    return {
        "n_groups": float(len(a[0])),
        "phi": mean_std(phi)["mean"],
        "sep": mean_std([phi_sep(av) for av in a])["mean"],
        "s": mean_std([_s_value(av, pv) for av, pv in pairs])["mean"],
        "off": mean_std([_off_over_sep(av, pv) for av, pv in pairs])["mean"],
    }


def _gran_triplet(payload: dict[str, Any], level: str) -> tuple[float, float, float]:
    """One seed's own (Phi, Phi_sep, S) at ``level``: `_granularity_stats`'s
    per-seed unit for intervals and paired differences. The quantities use the same
    diagonal-norm and Phi helpers as `_granularity_stats`.
    """
    a = _gran_diag_frob(payload, level)
    phi = _gran_phi(payload, level)
    return phi, phi_sep(a), _s_value(a, phi)


def _paired_seed_deltas(bundle: dict[str, Any], level: str) -> dict[str, list[float]]:
    r"""``{"Phi": [...], "Sep": [...], "LnS": [...]}``: resnet18 minus plain_resnet18
    at ``level``, one value per seed the two architectures' "final" checkpoint share
    (sorted), for each of the three per-seed statistics `_gran_triplet` returns --
    Phi and Phi_sep plain, S through its own logarithm so a ratio's confidence
    interval is symmetric in log space (the convention FinalDeltaLnSStage/Layer
    already fix).

    The one pairing routine behind every ``FinalDelta{Phi,Sep,LnS}{Stage,Layer}``
    macro below: one bundle shaped like
    ``exp8_a1_long_gran_m3000`` (both architectures, a "final" checkpoint, seeds
    shared between them) goes in, the three paired-difference lists come out. All
    retained partition contrasts use this one pairing routine.
    """
    resnet_by_seed = {
        seed: _gran_triplet(payload, level)
        for seed, payload in bundle["resnet18"]["final"]["seeds"].items()
    }
    plain_by_seed = {
        seed: _gran_triplet(payload, level)
        for seed, payload in bundle["plain_resnet18"]["final"]["seeds"].items()
    }
    common_seeds = sorted(set(resnet_by_seed) & set(plain_by_seed))
    return {
        "Phi": [resnet_by_seed[s][0] - plain_by_seed[s][0] for s in common_seeds],
        "Sep": [resnet_by_seed[s][1] - plain_by_seed[s][1] for s in common_seeds],
        "LnS": [
            math.log(resnet_by_seed[s][2]) - math.log(plain_by_seed[s][2])
            for s in common_seeds
        ],
    }


def _t_interval(values: Sequence[float]) -> dict[str, float]:
    r"""Mean, sample standard deviation (``ddof=1``) and a 95% t-interval
    (``scipy.stats.t.ppf``, ``len(values) - 1`` degrees of freedom) over ``values``.

    Used for per-seed S intervals and paired architecture differences at a fixed
    partition. Returns ``{"mean", "sd", "ci_low", "ci_high"}``; ``sd``/``ci_low``/``ci_high`` are NaN
    below two values, and the interval collapses to the mean (rather than NaN) at
    zero spread, matching `analysis.py`'s own convention for that edge case.
    """
    values = list(values)
    n = len(values)
    mean = sum(values) / n
    result: dict[str, float] = {
        "mean": mean,
        "sd": math.nan,
        "ci_low": math.nan,
        "ci_high": math.nan,
    }
    if n < 2:
        return result
    sd = statistics.stdev(values)
    result["sd"] = sd
    se = sd / math.sqrt(n)
    if se == 0.0:
        result["ci_low"] = result["ci_high"] = mean
        return result
    t_crit = float(stats.t.ppf(0.975, df=n - 1))
    result["ci_low"] = mean - t_crit * se
    result["ci_high"] = mean + t_crit * se
    return result


