def _fourth_largest_coupling_min(method: dict[str, Any]) -> float:
    r"""min over every cross-term record of the fourth-largest coupling C(v, w)
    among that record's 15 unordered block pairs. The overlay's gate caps the selection at the three
    largest coupled pairs (`overlay.py`'s ``overlay_max_pairs = 3``), and
    dropping a small pair can never promote a new one past that cap, so a
    threshold can change a refresh's selection only when it exceeds that
    refresh's own fourth-largest coupling. This is the minimum of that
    fourth-largest value over every refresh record of ``method``: the highest
    a threshold could sit and still leave every selection, at every refresh,
    exactly as it is.

    Reuses `analysis._cross_term_records`'s own traversal of
    ``cross_term[*].pairs`` -- the one `coupling_field_values` and
    `coupling_eps_by_pair` also reduce -- rather than a second walk of the same
    field. C(v, w) is exactly symmetric on this field: no ordered pair
    disagrees with its transpose by more than 1e-12 (asserted below, on every
    record, not assumed), so a record's 30 ordered pairs reduce to exactly 15
    distinct unordered ones (also asserted).
    """
    minimum = math.inf
    for pairs in _cross_term_records(method):
        unordered: dict[tuple[str, str], float] = {}
        for key, values in pairs.items():
            v, w = key.split("->")
            ukey = (v, w) if v < w else (w, v)
            c = float(values["coupling"])
            if ukey in unordered:
                assert abs(unordered[ukey] - c) <= 1e-12, (
                    f"C({key}) disagrees with its transpose by more than 1e-12"
                )
            else:
                unordered[ukey] = c
        assert len(unordered) == 15, (
            f"expected 15 unordered pairs, got {len(unordered)}"
        )
        fourth_largest = sorted(unordered.values(), reverse=True)[3]
        minimum = min(minimum, fourth_largest)
    return minimum


def _accept_share_other_steps(method: dict[str, Any]) -> tuple[float, float]:
    """Accepted shares on refresh records and on the remaining steps.

    The populations partition proposals. Refresh counts come from model_decrease;
    remaining counts subtract those records from the pooled reject_breakdown counts.
    """
    verdicts = reject_breakdown(method)
    records = [r for p in method["seeds"].values() for r in p["model_decrease"]]
    accepted_refresh = sum(1 for r in records if r["accepted"])
    refresh_share = accepted_refresh / len(records)
    n_accepted_other = verdicts["n_accepted"] - accepted_refresh
    n_proposed_other = verdicts["n_proposed"] - len(records)
    other_share = n_accepted_other / n_proposed_other
    return refresh_share, other_share


def _coupling_field_maximum(
    method: dict[str, Any],
) -> tuple[float, list[tuple[str, int, str]]]:
    """The maximum of ``method``'s coupling field, and every (seed, step, ordered pair)
    at which it is attained.

    The population is the one `analysis.coupling_field_values` pools into
    ``CouplingFieldMax`` -- every finite ``coupling`` of every ordered pair of every
    ``cross_term`` record of every seed -- walked here with the record's ``step`` kept,
    which that flat list drops. A step-0 record is the first measurement of a run, taken
    before any update, so on the weights the run starts from (``exp7`` fine-tunes the
    ImageNet-pretrained ResNet-50).
    """
    best = -math.inf
    where: list[tuple[str, int, str]] = []
    for seed, payload in method["seeds"].items():
        for record in payload["cross_term"]:
            for pair, values in record["pairs"].items():
                c = float(values["coupling"])
                if not math.isfinite(c) or c < best:
                    continue
                if c > best:
                    best, where = c, []
                where.append((seed, int(record["step"]), pair))
    return best, where


def _newton_divergence(method: dict[str, Any]) -> dict[str, str]:
    """``NewtonDivergeStep`` and ``NewtonNegCurvShareFiniteLo`` for the Newton-CG arm.

    One of the arm's three runs becomes non-finite -- its payoff records have a NaN
    ``loss_theta`` from step 1800 on -- and from there no stop can be marked: the solve's
    test ``p^T A p <= 0`` is false on NaN, so every stop on negative curvature is on a
    finite state, and ``n_negative_curvature / n_solves`` (``NewtonNegCurvShare``, 80.9
    per cent) is diluted by the solves on non-finite states. ``NewtonDivergeStep`` is the
    step of that run's first non-finite record: the run was finite at the record before,
    so it became non-finite at some step in between, and by this step at the latest.
    ``NewtonNegCurvShareFiniteLo`` is ``n_negative_curvature / (n_solves - T n)`` over
    the three runs, ``n`` the non-finite records and ``T`` the spacing of the records,
    read off their own steps: each record stands for ``T`` solves, so at least ``T n``
    solves are on non-finite states, the denominator is at least the number of solves on
    finite states, and the quotient is a lower bound of the share among those.

    The bound needs what is checked here, ``ValueError`` naming the macro and what the
    text would have to change: exactly one of exactly three runs is non-finite (the text
    says so); its non-finite records are the contiguous tail of its run (once non-finite,
    always); every run's records are evenly spaced, at one common spacing, and the run
    has ``T`` solves per record; and none of the non-finite records carries the
    negative-curvature flag (the premise above, on the records, which sample every
    ``T``-th solve).
    """
    seeds = method["seeds"]
    diverged = nonfinite_record_steps(method)
    if len(diverged) != 1 or len(seeds) != 3:
        raise ValueError(
            "NewtonDivergeStep: the manuscript says that one of the three Newton-CG "
            f"runs became non-finite, but {len(diverged)} of {len(seeds)} did "
            f"({sorted(diverged)!r}); the sentence must change with it"
        )
    ((diverged_seed, bad_steps),) = diverged.items()
    period = 0
    n_solves = n_negative = 0
    for seed, payload in seeds.items():
        records = payload["model_decrease"]
        steps = [int(r["step"]) for r in records]
        gaps = {b - a for a, b in zip(steps, steps[1:], strict=False)}
        if len(gaps) != 1 or (period and gaps != {period}):
            raise ValueError(
                "NewtonNegCurvShareFiniteLo: the payoff records of the Newton-CG runs "
                f"are not evenly spaced at one common step ({seed}: {sorted(gaps)!r} "
                f"after {period or 'the first run'}); records cannot stand for a fixed "
                "number of solves each"
            )
        period = period or gaps.pop()
        block = payload["newton_cg"]
        if int(block["n_solves"]) != period * len(records):
            raise ValueError(
                "NewtonNegCurvShareFiniteLo: the Newton-CG run "
                f"{seed} has {block['n_solves']} solves for {len(records)} records "
                f"{period} steps apart; a record then does not stand for {period} "
                "solves, and the solves after the first non-finite record cannot be "
                "counted from them"
            )
        n_solves += int(block["n_solves"])
        n_negative += int(block["n_negative_curvature"])
    records = seeds[diverged_seed]["model_decrease"]
    tail = [int(r["step"]) for r in records if int(r["step"]) >= bad_steps[0]]
    if bad_steps != tail:
        raise ValueError(
            "NewtonNegCurvShareFiniteLo: the non-finite records of the Newton-CG run "
            f"{diverged_seed} (from step {bad_steps[0]}, {len(bad_steps)} of them) are "
            "not a contiguous tail of its run; a run is taken to stay non-finite once "
            "it has become so, and the solves after the first such record cannot be "
            "counted otherwise"
        )
    flagged = [
        int(r["step"])
        for r in records
        if int(r["step"]) in bad_steps and r.get("newton_negative_curvature")
    ]
    if flagged:
        raise ValueError(
            "NewtonNegCurvShareFiniteLo: a stop on negative curvature is flagged on a "
            f"non-finite record of {diverged_seed} (steps {flagged!r}), so the premise "
            "that no stop can be marked after divergence does not hold in this bundle, "
            "and n_negative_curvature / (n_solves - T n) is not a lower bound"
        )
    finite_solves = n_solves - period * len(bad_steps)
    return {
        "NewtonDivergeStep": round_str(float(bad_steps[0]), 0),
        "NewtonNegCurvShareFiniteLo": round_str(100 * n_negative / finite_solves, 1),
    }


def _stage_b(exp7: dict[str, Any]) -> dict[str, str]:
    """Stage-B macros: the K-FAC overlay's refresh records and worked example, the
    safeguard's verdicts (pooled, and reconciled against the refresh-record
    subsample's own accept/reject shares, and against its share on the remaining
    steps, on both overlay arms), the closed-gap (gamma) distribution, the
    validity share, the coupling/cross-term (eps) pairs (the gate's threshold
    against both overlay arms and the highest threshold that would leave every
    selection unchanged, and the additive fit's row/column-alone shares), and the
    Newton-CG oracle's negative-curvature share, the share of the variance of log eps
    that an additive fit made record by record explains, and the Newton-CG arm's one
    non-finite run (`_newton_divergence`). Sentences of the text state a fact about
    where or how large a number is -- the coupling field's maximum lies at step zero,
    on a pair with the new head; a stop on negative curvature is the most common stop of
    the oracle's solve on the K-FAC trajectory; one of three Newton-CG runs is
    non-finite; on every record the validity share counts the minibatch loss decreases
    -- and each is checked, ``ValueError`` naming the macro and the sentence.

    ``exp7`` is required (never optional, see `paper_data.config`), so every macro
    here is always defined.
    """
    macros: dict[str, str] = {}
    overlay = exp7[_KFAC_PAIR]

    # Check that the coupling maximum occurs at step zero on a pair with the new
    # head. The head is new because the run replaces the pretrained classifier.
    max_value, max_at = _coupling_field_maximum(overlay)
    if any(step != 0 or _HEAD not in pair.split("->") for _, step, pair in max_at):
        raise ValueError(
            "CouplingFieldMax: the manuscript says 'The maximum lies at step zero, on a "
            "pair with the new head.', but the maximum "
            f"{max_value!r} of the K-FAC pair's coupling field is attained at (seed, "
            f"step, pair) {max_at!r}; the sentence must change with it"
        )
    # C-conditioning.tex calls a stop on non-positive curvature "the most common stop on
    # the K-FAC trajectory (OracleNegCurvShare per cent of the solves)". The solve has
    # three kinds of stop (non-positive curvature, residual below the tolerance,
    # iteration limit), of which the bundle counts the first against the solve count, so
    # "most common" holds when that share is strictly more than half, whatever the other
    # two split. The macro's own fields: the ``newton_cg`` block of each K-FAC seed.
    oracle = negative_curvature_share(exp7["kfac"])
    if not oracle["share"] > 0.5:
        raise ValueError(
            "OracleNegCurvShare: C-conditioning.tex calls a stop on non-positive "
            "curvature 'the most common stop on the K-FAC trajectory'; of the oracle's "
            "three kinds of stop that holds if it is more than half of the solves, but "
            f"{oracle['n_negative_curvature']} of {oracle['n_solves']} solves "
            f"({oracle['share']:.3f}) stopped on it; the sentence must change with it"
        )
    # One of the Newton-CG arm's three runs is non-finite from step 1800 on, where no stop
    # can be marked: where it starts, and the lower bound of the share of stops on
    # negative curvature among the solves on finite states.
    macros.update(_newton_divergence(exp7["newton_cg"]))

    # --- refresh records (one per overlay refresh step, pooled over the 3 seeds) -
    records = [r for p in overlay["seeds"].values() for r in p["model_decrease"]]
    macros["RefreshRecords"] = round_str(float(len(records)), 0)
    lowered = sum(
        1
        for r in records
        if math.isfinite(r["m_proposal"])
        and math.isfinite(r["m_kfac"])
        and r["m_proposal"] < r["m_kfac"]
    )
    macros["ModelLoweredRecords"] = round_str(float(lowered), 0)
    macros["MedianModelBase"] = round_str(
        statistics.median(r["m_kfac"] for r in records), 2
    )
    macros["MedianModelProposal"] = round_str(
        statistics.median(r["m_proposal"] for r in records), 3
    )
    loss_reject = sum(1 for r in records if r["rejected_by"] == "loss")
    macros["LossRejectRecords"] = round_str(float(loss_reject), 0)
    macros["LossRejectShare"] = round_str(100 * loss_reject / len(records), 1)
    accepted = [r for r in records if r["accepted"]]
    macros["AcceptedRecords"] = round_str(float(len(accepted)), 0)
    macros["AcceptedEarlyRecords"] = round_str(
        float(sum(1 for r in accepted if r["step"] in (0, 20, 40))), 0
    )
    # Accepted share on the 450 refresh records themselves (where the oracle's Newton
    # solve is run) against the share on every other step: the refresh records are not a random
    # subsample of the full population, but they are not the correction's most
    # favourable moment either -- the same flag that rebuilds the base
    # preconditioner's factors there also rebuilds the correction's own coupling,
    # selection and subspaces (`runner_exp7.py`'s ``measuring`` flag passed as
    # ``refresh=``), so at a refresh record both the base step and the correction
    # are freshest, not only the base step. AcceptShareOther is the eigenvalue-
    # corrected arm's own comparison (AcceptShareRefreshEkfac/AcceptShareOtherEkfac)
    # computed identically below.
    refresh_share_kfac, other_share_kfac = _accept_share_other_steps(overlay)
    macros["AcceptShareRefresh"] = round_str(100 * refresh_share_kfac, 1)
    macros["AcceptShareOther"] = round_str(100 * other_share_kfac, 1)
    refresh_share_ekfac, other_share_ekfac = _accept_share_other_steps(
        exp7[_EKFAC_PAIR]
    )
    macros["AcceptShareRefreshEkfac"] = round_str(100 * refresh_share_ekfac, 1)
    macros["AcceptShareOtherEkfac"] = round_str(100 * other_share_ekfac, 1)

    # --- safeguard verdicts, pooled over seeds ------------------------------------
    verdicts = reject_breakdown(overlay)
    macros["ProposalsTotal"] = round_str(float(verdicts["n_proposed"]), 0)
    macros["AcceptShare"] = round_str(100 * verdicts["accept_share"], 1)
    macros["RejectByRatio"] = round_str(float(verdicts["n_reject_by"]["ratio"]), 0)
    macros["RejectByModel"] = round_str(float(verdicts["n_reject_by"]["model"]), 0)
    macros["RejectByLoss"] = round_str(float(verdicts["n_reject_by"]["loss"]), 0)
    macros["RejectByLossShare"] = round_str(
        100 * verdicts["reject_share_by"]["loss"], 1
    )

    # Refresh/model/native-loss summaries above count K-FAC raw proposals on all
    # refresh records. Gamma instead uses the APPLIED m_overlay (base on rejection),
    # and its own positive-reference-gap domain. Never use it to filter C/epsilon.
    for suffix, method in (("Kfac", overlay), ("Ekfac", exp7[_EKFAC_PAIR])):
        eligible = [gamma_records(p) for p in method["seeds"].values()]
        macros[f"GammaEligibleRecords{suffix}"] = str(sum(len(g) for g, _ in eligible))
        macros[f"GammaSkippedRecords{suffix}"] = str(sum(n for _, n in eligible))

    # --- the gamma distribution behind gap_closed ---------------------------------
    gammas = [
        g for payload in overlay["seeds"].values() for g in gamma_records(payload)[0]
    ]
    macros["GammaZeroShare"] = round_str(
        100 * sum(1 for g in gammas if g == 0.0) / len(gammas), 1
    )
    macros["GammaAboveOneShare"] = round_str(
        100 * sum(1 for g in gammas if g > 1.0) / len(gammas), 2
    )

    # --- validity share m(d0) > 0, one per curvature method -----------------------
    # Check that the share exceeds one half and the minibatch loss decreases on
    # every counted record, for all four methods.
    for macro_name, method in (
        ("ValidityShareKfac", exp7["kfac"]),
        ("ValidityShareKfacOverlay", overlay),
        ("ValidityShareEkfac", exp7["ekfac"]),
        ("ValidityShareEkfacOverlay", exp7[_EKFAC_PAIR]),
    ):
        share = validity_share(method)
        not_falling = share["loss_not_falling"]
        if not share["pooled"] > 0.5:
            raise ValueError(
                f"{macro_name}: the manuscript says 'The base step is "
                "outside the model for most of training', but the damped model "
                "predicts an increase along the base step on "
                f"{100 * share['pooled']:.1f} per cent of the records, which is not "
                "more than half; the heading must change with it"
            )
        if not_falling:
            seed, step = not_falling[0]
            raise ValueError(
                f"{macro_name}: the manuscript says that on these "
                "records the damped model predicts an increase along the base step "
                "'while the minibatch loss decreases', but the loss does not fall on "
                f"{len(not_falling)} of the records the share counts (first: seed "
                f"{seed}, step {step}); the sentence must change with it"
            )
    macros["ValidityShareKfac"] = round_str(
        100 * validity_share(exp7["kfac"])["pooled"], 1
    )
    macros["ValidityShareKfacOverlay"] = round_str(
        100 * validity_share(overlay)["pooled"], 1
    )
    macros["ValidityShareEkfac"] = round_str(
        100 * validity_share(exp7["ekfac"])["pooled"], 1
    )
    macros["ValidityShareEkfacOverlay"] = round_str(
        100 * validity_share(exp7[_EKFAC_PAIR])["pooled"], 1
    )

    # --- Spearman(coupling, eps), K-FAC and EKFAC pairs ---------------------------
    rho_kfac = spearman_coupling_eps(overlay)
    rho_ekfac = spearman_coupling_eps(exp7[_EKFAC_PAIR])
    # Two decimals, not three: rho_s's standard error on this ~13500-observation
    # pooled sample is at least 1/sqrt(n) ~= 0.009, and larger still because the
    # observations are dependent, so a third decimal is not supported by the
    # data. Every place this quantity is printed -- these two macros and the
    # hardcoded .2f in tables/exp789.py's _rho_by_arm/_rho_cell and
    # figures/exp789.py's _rho_sentence -- uses this same precision; do not raise any
    # of them back to three decimals.
    macros["SpearmanKfac"] = round_str(rho_kfac["rho"], 2)
    macros["SpearmanKfacP"] = round_str(rho_kfac["p"], 3)
    macros["SpearmanEkfac"] = round_str(rho_ekfac["rho"], 2)
    # Five decimals preserve the small eigenvalue-corrected p-value; three would
    # round it to zero. Both values come from spearman_coupling_eps.
    macros["SpearmanEkfacP"] = round_str(rho_ekfac["p"], 5)
    macros["SpearmanObs"] = round_str(float(rho_kfac["n_pairs"]), 0)
    macros["SpearmanPairsPerRecord"] = round_str(
        rho_kfac["n_pairs"] / rho_kfac["n_records"], 0
    )

    # --- coupling field over all ordered pairs and refresh records of the K-FAC arm.
    # A maximum on one pair does not describe the sum of squared pair norms.
    coupling_values = coupling_field_values(overlay)
    macros["CouplingFieldMedian"] = round_str(statistics.median(coupling_values), 3)
    macros["CouplingFieldMax"] = round_str(max(coupling_values), 3)

    # --- the gate's own threshold against the coupling field, both overlay arms.
    # tau is read from
    # Exp7Config, not typed as 0.1, so a change to the configured threshold breaks
    # this rather than silently invalidating the sentence it feeds.
    ekfac_coupling_values = coupling_field_values(exp7[_EKFAC_PAIR])
    macros["CouplingFieldMinKfac"] = round_str(min(coupling_values), 3)
    macros["CouplingFieldMinEkfac"] = round_str(min(ekfac_coupling_values), 3)
    tau = Exp7Config.tau
    both_arms = coupling_values + ekfac_coupling_values
    macros["CouplingBelowTau"] = round_str(
        float(sum(1 for c in both_arms if c <= tau)), 0
    )
    macros["CouplingObsBothArms"] = round_str(float(len(both_arms)), 0)

    # --- the highest threshold that would leave every refresh's selection
    # unchanged, both overlay arms. Same
    # 3-decimal precision as CouplingFieldMinKfac/Ekfac, the other threshold-facing
    # coupling macros.
    macros["CouplingFourthMinKfac"] = round_str(
        _fourth_largest_coupling_min(overlay), 3
    )
    macros["CouplingFourthMinEkfac"] = round_str(
        _fourth_largest_coupling_min(exp7[_EKFAC_PAIR]), 3
    )

    # --- median eps by ordered block pair, K-FAC pair ------------------------------
    by_pair = coupling_eps_by_pair(overlay)
    for macro_name, pair in _EPS_STEM_LAYER.items():
        macros[macro_name] = round_str(float(statistics.median(by_pair[pair][1])), 1)
    # Reads "layer3->stem" by name: the reverse direction of EpsStemLayerThree above,
    # not derived from it (eps is not symmetric, see the comment on _EPS_STEM_LAYER).
    macros["EpsLayerThreeStem"] = round_str(
        float(statistics.median(by_pair["layer3->stem"][1])), 3
    )

    # --- how much of the spread of log eps the row/column scales explain ---------
    cross_term_records = [r for p in overlay["seeds"].values() for r in p["cross_term"]]
    decomposition = eps_variance_decomposition(cross_term_records)
    macros["EpsAdditiveShare"] = round_str(100 * decomposition["additive_share"], 1)

    # --- Newton-CG oracle's negative-curvature share, its own steps and K-FAC's --
    macros["NewtonNegCurvShare"] = round_str(
        100 * negative_curvature_share(exp7["newton_cg"])["share"], 1
    )
    macros["OracleNegCurvShare"] = round_str(100 * oracle["share"], 1)

    return macros


