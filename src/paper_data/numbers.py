class _WeightStateCounts(NamedTuple):
    """The map's cells by the state of their weights (`_phi_cells_by_weight_state`)."""

    trained: int  # weights trained in every group
    trained_below_sep: int  # of those, Phi below Phi_sep
    random_init: int  # a random initialisation, no group trained
    pretrained_body: int  # a pretrained body under a new, randomly initialised head
    cnn_mid_final: int  # selected from-scratch convolutional mid/final cells
    cnn_between_references: int  # their seed means strictly between both references


def _cnn_cell_between_references(
    name: str, row: str, ckpt: str, entry: dict[str, Any]
) -> bool:
    """Compare one selected cell's seed-mean Phi to its recorded size reference
    and mean of individual seed-level profile references (not averaged norms).
    Refuse incomplete or nonfinite cells rather than shrinking the cohort.
    """
    where = (name, row, ckpt)
    seeds = entry.get("seeds")
    if not isinstance(seeds, dict) or len(seeds) != 3:
        raise ValueError(f"PhiCellsCnnMidFinal: {where!r} needs three recorded seeds")
    phis: list[float] = []
    sizes: list[int] | None = None
    for seed, payload in seeds.items():
        try:
            value = float(payload["phi"])
            norms = payload["diag_frob"]
            recorded = list(payload["group_sizes"])
            if not recorded or not all(isinstance(p, int) and p > 0 for p in recorded):
                raise ValueError("invalid group sizes")
            if sizes is not None and recorded != sizes:
                raise ValueError("inconsistent group sizes")
            sizes = recorded
            if not norms or not all(math.isfinite(float(a)) for a in norms.values()):
                raise ValueError("missing or nonfinite diagonal norms")
            if not math.isfinite(value) or not math.isfinite(phi_sep(norms)):
                raise ValueError("nonfinite Phi or Phi_sep")
        except (KeyError, TypeError, ValueError) as exc:
            raise ValueError(
                f"PhiCellsCnnMidFinal: {where!r} seed {seed!r} lacks finite Phi, "
                "diagonal norms, or consistent recorded group sizes"
            ) from exc
        phis.append(value)
    assert sizes is not None
    try:
        reported = float(entry["phi_mean"])
    except (KeyError, TypeError, ValueError) as exc:
        raise ValueError(f"PhiCellsCnnMidFinal: {where!r} lacks mean Phi") from exc
    mean_phi = sum(phis) / len(phis)
    if not math.isfinite(reported) or not math.isclose(
        mean_phi, reported, rel_tol=1e-12, abs_tol=1e-12
    ):
        raise ValueError(
            f"PhiCellsCnnMidFinal: {where!r} has missing, nonfinite, or "
            "inconsistent seed-mean Phi"
        )
    return phi_null(sizes) < reported < _mean_phi_sep(seeds.values())


def _phi_cells_by_weight_state(
    exp8: dict[str, Any],
    exp8_a1_width: dict[str, Any],
    exp8_a1_imagenet32: dict[str, Any],
    exp8_a2: dict[str, Any],
    exp9: dict[str, Any],
    exp9_a3_llm: dict[str, Any],
) -> _WeightStateCounts:
    """The cells of the map ``tab:phi-map`` prints, counted by the state of the weights
    they hold and not by their checkpoint label. ``_stage_a`` prints the counts
    as ``PhiCellsTrainedWeights``, ``PhiCellsTrainedBelowSep`` and
    ``PhiCellsRandomInit``, and checks them against ``PhiCellsTotal``. The
    separately selected convolutional mid/final cells produce
    ``PhiCellsCnnMidFinal`` and ``PhiCellsCnnBetweenReferences``.

    The weight states are classified bundle by bundle:

    - ``exp8``, ``exp8_a1_width``, ``exp8_a1_imagenet32`` (A1, A1-width, A1-IN32,
      trained from scratch): the ``init`` checkpoint is a random initialisation, every
      other checkpoint is trained in every group;
    - ``exp9_a3_llm`` (A3-LLM, two pretrained models, frozen): every row is trained in
      every group;
    - ``exp9`` (A3-toy, "none (fixed init)"): every row is a random initialisation;
    - ``exp8_a2`` (A2, "ImageNet weights"): the one cell is neither. Its body is the
      pretrained one, but its head is a new ``nn.Linear`` on 196 classes
      (`experiments.models`: ``base.fc = nn.Linear(...)``), drawn per seed -- the seed is
      set before the model is built (`experiments.runner_exp8`) -- and never trained, so
      the test accuracy is at chance. It is "pretrained body, new randomly initialised
      head", not a trained network.

    A cell is below ``Phi_sep`` when its seed-mean Phi (``phi_mean``, or ``phi.mean``
    for exp9's flat layout) is under `_mean_phi_sep` of its seeds.

    The generator checks three claims, raising ``ValueError`` if any fails:

    - Phi lies below ``Phi_sep`` on every cell with fully trained weights (the text
      prints the two counts as "N of N" and concludes from it);
    - the third state is exactly `_PRETRAINED_RESNET_CELL` (the text counts one cell);
    - "The largest Phi in the map is the ResNet-50's, whose head is new": over all the
      cells, the seed-mean Phi (the same ``phi_mean`` the macro ``PhiPretrainedRfifty``
      prints for it) is largest at `_PRETRAINED_RESNET_CELL`.

    The mid/final cohort must contain all eight named convolutional rows and three
    finite seeds per selected cell, with recorded group sizes and diagonal norms.
    """
    trained: list[tuple[tuple[str, str, str], bool]] = []  # (cell, below Phi_sep)
    body: list[tuple[str, str, str]] = []
    phi: dict[tuple[str, str, str], float] = {}  # every cell's seed-mean Phi
    n_random = 0
    cnn_cells: set[tuple[str, str, str]] = set()
    cnn_between = 0
    for name, bundle in (
        ("exp8", exp8),
        ("exp8_a1_width", exp8_a1_width),
        ("exp8_a1_imagenet32", exp8_a1_imagenet32),
    ):
        for row, checkpoints in data_items(bundle):
            for ckpt, entry in checkpoints.items():
                phi[(name, row, ckpt)] = entry["phi_mean"]
                if ckpt == "init":
                    n_random += 1
                    continue
                if row in _CNN_ROWS[name] and ckpt in _CNN_CHECKPOINTS:
                    cnn_cells.add((name, row, ckpt))
                    cnn_between += _cnn_cell_between_references(name, row, ckpt, entry)
                below = entry["phi_mean"] < _mean_phi_sep(entry["seeds"].values())
                trained.append(((name, row, ckpt), below))
    expected_cnn = {
        (name, row, ckpt)
        for name, rows in _CNN_ROWS.items()
        for row in rows
        for ckpt in _CNN_CHECKPOINTS
    }
    if cnn_cells != expected_cnn:
        raise ValueError(
            "PhiCellsCnnMidFinal: the required mid/final convolutional cells are "
            f"incomplete (missing {sorted(expected_cnn - cnn_cells)!r})"
        )
    for row, checkpoints in data_items(exp8_a2):
        for ckpt, entry in checkpoints.items():
            phi[("exp8_a2", row, ckpt)] = entry["phi_mean"]
            body.append(("exp8_a2", row, ckpt))
    for name, bundle in (("exp9", exp9), ("exp9_a3_llm", exp9_a3_llm)):
        for row, entry in data_items(bundle):
            phi[(name, row, "-")] = entry["phi"]["mean"]
            if name == "exp9":
                n_random += 1
                continue
            below = entry["phi"]["mean"] < _mean_phi_sep(entry["seeds"].values())
            trained.append(((name, row, "-"), below))

    exceptions = [cell for cell, below in trained if not below]
    if exceptions:
        raise ValueError(
            "PhiCellsTrainedWeights/PhiCellsTrainedBelowSep: the manuscript prints "
            "these two as 'N of N' and concludes that Phi lies below Phi_sep on every "
            "cell whose weights are all trained, but the "
            "cells with fully trained weights and Phi not below Phi_sep are "
            f"{exceptions!r}; the conclusion must change with it"
        )
    if body != [_PRETRAINED_RESNET_CELL]:
        raise ValueError(
            "PhiCellsTotal: the manuscript puts exactly one cell, the ImageNet-"
            f"pretrained ResNet-50's {_PRETRAINED_RESNET_CELL!r}, in the third weight "
            "state (pretrained body, new randomly initialised head), but the cells of "
            f"exp8_a2 are {body!r}; the passage that counts the map's cells by the "
            "state of their weights must change with it"
        )
    largest = max(phi, key=lambda cell: phi[cell])
    if largest != _PRETRAINED_RESNET_CELL:
        raise ValueError(
            "PhiPretrainedRfifty: the manuscript says 'The largest Phi "
            "in the map is the ResNet-50's, whose head is new', but the largest "
            "seed-mean Phi "
            f"among the {len(phi)} cells of the map is {phi[largest]!r} at "
            f"{largest!r}, against {phi[_PRETRAINED_RESNET_CELL]!r} at "
            f"{_PRETRAINED_RESNET_CELL!r}; the heading must change with it"
        )
    return _WeightStateCounts(
        trained=len(trained),
        trained_below_sep=sum(1 for _, below in trained if below),
        random_init=n_random,
        pretrained_body=len(body),
        cnn_mid_final=len(cnn_cells),
        cnn_between_references=cnn_between,
    )


def _a2_head_macros(exp8_a2: dict[str, Any]) -> dict[str, str]:
    """``HeadShareRfiftyLo``/``Hi`` and ``SNoHeadRfiftyLo``/``Hi``: how much of the
    pretrained ResNet-50's off-block squared mass lies on pairs with its head, and what S
    is without the head, over the five seeds of ``exp8_a2``.

    The head is a new randomly initialised layer, so a measurement of the "pretrained
    network" is partly a measurement of it. A pair's squared mass is ||H_vw||_F^2 =
    C(v, w)^2 a_v a_w, ``diag_frob`` being the plain a_v = ||H_vv||_F and ``coupling``
    holding one entry per unordered pair; the share is the pairs with the head's part of
    their sum over all the pairs, in percent without decimals, smallest and largest over
    the seeds. S without the head is S = (sum a_v)^2 / ||H||^2 on the five groups that
    remain, with ||H||^2 = sum a_v^2 + 2 (sum of the pair masses without the head), the
    same `_s_value` as every other S, at two decimals.

    ``ValueError`` naming the macros when a seed's record does not hold every one of the
    n(n-1)/2 pairs of its n blocks with the head among them, or a mass is not finite
    (the sum is then not the whole off-block mass); and when on any seed the head's pairs
    carry no more than half of it, which the text will say they do.
    """
    shares: list[float] = []
    s_values: list[float] = []
    for seed, payload in exp8_a2["resnet50"]["init"]["seeds"].items():
        a = payload["diag_frob"]
        n_pairs = len(a) * (len(a) - 1) // 2
        mass: dict[frozenset[str], float] = {}
        for key, c in payload["coupling"].items():
            v, w = key.split("->")
            mass[frozenset((v, w))] = float(c) ** 2 * a[v] * a[w]
        if (
            _HEAD not in a
            or len(mass) != n_pairs
            or len(payload["coupling"]) != n_pairs
            or not all(math.isfinite(m) for m in mass.values())
        ):
            raise ValueError(
                "HeadShareRfiftyLo/HeadShareRfiftyHi/SNoHeadRfiftyLo/SNoHeadRfiftyHi: "
                f"the record of {seed} holds {len(payload['coupling'])} coupling "
                f"entries ({len(mass)} distinct pairs) for {len(a)} diagonal blocks, "
                f"which have {n_pairs} pairs, or has no '{_HEAD}' block or a mass that "
                "is not finite; the shares of the off-block mass are not defined on it"
            )
        total = sum(mass.values())
        share = sum(m for pair, m in mass.items() if _HEAD in pair) / total
        if not share > 0.5:
            raise ValueError(
                "HeadShareRfiftyLo/HeadShareRfiftyHi: the manuscript says the pairs "
                "with the head carry most of the pretrained ResNet-50's off-block "
                f"squared mass, but on {seed} they carry "
                f"{100 * share:.1f} per cent of it; the sentence must change with it"
            )
        shares.append(share)
        rest = {name: norm for name, norm in a.items() if name != _HEAD}
        sumsq = sum(norm * norm for norm in rest.values())
        off_rest = sum(m for pair, m in mass.items() if _HEAD not in pair)
        h_frob2 = sumsq + 2.0 * off_rest
        s_values.append(_s_value(rest, 1.0 - sumsq / h_frob2))
    return {
        "HeadShareRfiftyLo": round_str(100 * min(shares), 0),
        "HeadShareRfiftyHi": round_str(100 * max(shares), 0),
        "SNoHeadRfiftyLo": round_str(min(s_values), 2),
        "SNoHeadRfiftyHi": round_str(max(s_values), 2),
    }


def _stage_a(
    exp8: dict[str, Any],
    exp8_a1_width: dict[str, Any] | None,
    exp8_a1_imagenet32: dict[str, Any] | None,
    exp8_a2: dict[str, Any] | None,
    exp9: dict[str, Any],
    exp9_a3_llm: dict[str, Any] | None,
    exp8_a1_v2: dict[str, Any] | None,
    exp8_a1_long: dict[str, Any] | None,
    exp8_a2_gran_v3: dict[str, Any] | None,
    exp8_a1_long_gran_m3000: dict[str, Any] | None,
) -> dict[str, str]:
    """Stage-A macros: Phi against Phi_null/Phi_sep, the A1 inversion (gate A and its
    accuracy-matched replication), the toy/LLM Phi ladder, the granularity check
    (with Phi_sep/S alongside it, from exp8_a2_gran_v3 on the pretrained ResNet-50
    and from exp8_a1_long_gran_m3000 on the CIFAR-100 pair), the map's cells
    counted by the state of
    their weights
    (`_phi_cells_by_weight_state`: trained, random, and the pretrained ResNet-50's
    pretrained-body-new-head), the convolutional mid/final reference comparison,
    and how much of that ResNet-50's off-block mass lies on
    its new head (`_a2_head_macros`).

    Missing optional inputs may still omit macros outside canonical track B;
    the B-specific preflight requires every retained input before generation.
    """
    macros: dict[str, str] = {}

    # --- Phi and Phi_null over every trained ResNet row (A1, width/depth, ImageNet-32)
    # "Trained" here means every non-"plain" architecture's final checkpoint of the
    # three from-scratch bundles -- A1's ResNet-18, the width/depth sweep, and the
    # ImageNet-32 ResNet-18 -- against the ceiling their own block sizes fix.
    finals: list[float] = []
    nulls: list[float] = []
    for bundle, experiment in (
        (exp8, "exp8"),
        (exp8_a1_width, "exp8_a1_width"),
        (exp8_a1_imagenet32, "exp8_a1_imagenet32"),
    ):
        if bundle is None:
            continue
        for arch, checkpoints in data_items(bundle):
            if "plain" in arch:
                continue
            final = checkpoints.get("final")
            if final is None:
                continue
            finals.append(final["phi_mean"])
            sizes = _group_sizes(
                bundle,
                experiment,
                arch,
                (p for e in checkpoints.values() for p in e["seeds"].values()),
            )
            if sizes is not None:
                nulls.append(phi_null(sizes))
    if finals:
        macros["PhiTrainedResNetLo"] = round_str(min(finals), 3)
        macros["PhiTrainedResNetHi"] = round_str(max(finals), 3)
    if nulls:
        macros["PhiNullResNetLo"] = round_str(min(nulls), 3)
        macros["PhiNullResNetHi"] = round_str(max(nulls), 3)

    # --- A1 CIFAR-100 (exp8, always present) --------------------------------------
    resnet_final = exp8["resnet18"]["final"]
    plain_final = exp8["plain_resnet18"]["final"]
    macros["PhiResnetFinalCifar"] = round_str(resnet_final["phi_mean"], 3)
    macros["PhiPlainFinalCifar"] = round_str(plain_final["phi_mean"], 3)

    resnet_sep = _mean_phi_sep(resnet_final["seeds"].values())
    resnet_sizes = _group_sizes(
        exp8,
        "exp8",
        "resnet18",
        (p for e in exp8["resnet18"].values() for p in e["seeds"].values()),
    )
    assert resnet_sizes is not None  # exp8's own architecture is always rebuildable
    resnet_null = phi_null(resnet_sizes)
    macros["PhiExcessNullREighteen"] = round_str(
        resnet_final["phi_mean"] - resnet_null, 3
    )
    macros["PhiSepMinusNullREighteen"] = round_str(resnet_sep - resnet_null, 3)
    macros["PhiSepMinusPhiREighteen"] = round_str(
        resnet_sep - resnet_final["phi_mean"], 3
    )

    macros["GateAMeanDelta"] = round_str(gate_a(exp8)["mean_delta"], 3)
    # Same construction, one checkpoint earlier: gate A's pre-registered per-seed
    # delta at the middle checkpoint (exp8 alone -- the pooled/replicated version
    # below is a separate macro group, gated on exp8_a1_v2's presence).
    gate_a_mid_cifar = gate_a(exp8, checkpoint="mid")
    macros["GateAMidMeanDelta"] = round_str(gate_a_mid_cifar["mean_delta"], 3)
    # Section 4.1 states that this middle-checkpoint difference is positive on
    # every seed on both datasets. CIFAR-100 is exp8's
    # half of that absolute; exp8 is never optional, so this check runs on every
    # generation, the way TstarMedianAdam and TstarCellsOkTwentieth/Hundredth
    # above enforce their own prose absolutes.
    if not all(delta > 0.0 for delta in gate_a_mid_cifar["delta"].values()):
        raise ValueError(
            "GateAMidMeanDelta: Section 4.1 states the middle-checkpoint "
            "difference Phi_ResNet - Phi_Plain is positive on every seed on "
            "both datasets, but CIFAR-100's (exp8) per-seed deltas are "
            f"{gate_a_mid_cifar['delta']!r}"
        )

    # --- ImageNet-32 anchor (on demand) -------------------------------------------
    if exp8_a1_imagenet32 is not None:
        inet_resnet = exp8_a1_imagenet32["resnet18"]["final"]
        inet_plain = exp8_a1_imagenet32["plain_resnet18"]["final"]
        macros["PhiResnetFinalInet"] = round_str(inet_resnet["phi_mean"], 3)
        macros["PhiPlainFinalInet"] = round_str(inet_plain["phi_mean"], 3)
        macros["AccResnetFinalInet"] = round_str(
            as_percent(inet_resnet["test_acc_mean"]), 1
        )
        macros["AccPlainFinalInet"] = round_str(
            as_percent(inet_plain["test_acc_mean"]), 1
        )
        # The three per-seed Phi differences (ResNet-18 minus Plain-18) at that same
        # final checkpoint, in seed order -- `gate_a`'s own per-seed breakdown,
        # sorted by seed number (`experiments.protocol.seed_number`), not a new
        # statistic.
        inet_delta = gate_a(exp8_a1_imagenet32)["delta"]
        for macro_name, seed_key in (
            ("InetDeltaFinalOne", "seed_42"),
            ("InetDeltaFinalTwo", "seed_43"),
            ("InetDeltaFinalThree", "seed_44"),
        ):
            if seed_key in inet_delta:
                macros[macro_name] = round_str(inet_delta[seed_key], 3)

        # ImageNet-32 comparison at the middle checkpoint. This bundle
        # is on demand (config.OPTIONAL_EXPERIMENTS), so the check lives inside
        # this guard: it never raises from the bundle being absent, only from a
        # non-positive delta once the bundle is present -- the same discipline
        # `_validity` uses for its own on-demand TstarCellsOk group above.
        inet_delta_mid = gate_a(exp8_a1_imagenet32, checkpoint="mid")["delta"]
        if not all(delta > 0.0 for delta in inet_delta_mid.values()):
            raise ValueError(
                "InetDeltaMid: Section 4.1 states the middle-checkpoint "
                "difference Phi_ResNet - Phi_Plain is positive on every seed on "
                "both datasets, but ImageNet-32's (exp8_a1_imagenet32) per-seed "
                f"deltas are {inet_delta_mid!r}"
            )

    # --- A2 pretrained ResNet-50 (on demand) --------------------------------------
    if exp8_a2 is not None:
        a2 = exp8_a2["resnet50"]["init"]
        macros["PhiPretrainedRfifty"] = round_str(a2["phi_mean"], 3)
        a2_sizes = _group_sizes(
            exp8_a2,
            "exp8_a2",
            "resnet50",
            (p for e in exp8_a2["resnet50"].values() for p in e["seeds"].values()),
        )
        if a2_sizes is not None:
            macros["PhiNullRfifty"] = round_str(phi_null(a2_sizes), 3)
        macros["PhiSepRfifty"] = round_str(_mean_phi_sep(a2["seeds"].values()), 3)
        # Its new random head carries most of its off-block mass.
        macros.update(_a2_head_macros(exp8_a2))
        macros["CouplingStemHeadRfifty"] = round_str(
            a2["coupling"]["stem->head"]["mean"], 1
        )
        macros["CouplingLayerOneHeadRfifty"] = round_str(
            a2["coupling"]["layer1->head"]["mean"], 1
        )

    # --- toy decoder ladder (exp9, always present) --------------------------------
    toy_phi = {model: entry["phi"]["mean"] for model, entry in data_items(exp9)}
    toy_lo = min(toy_phi, key=lambda m: toy_phi[m])
    toy_hi = max(toy_phi, key=lambda m: toy_phi[m])
    macros["PhiToyLo"] = round_str(toy_phi[toy_lo], 3)
    macros["PhiToyHi"] = round_str(toy_phi[toy_hi], 3)
    for macro_name, model in (("PhiNullToyLo", toy_lo), ("PhiNullToyHi", toy_hi)):
        sizes = _group_sizes(exp9, "exp9", model, exp9[model]["seeds"].values())
        if sizes is not None:
            macros[macro_name] = round_str(phi_null(sizes), 3)

    # --- frozen LLMs (on demand): the two model ids the manuscript names ----------
    if exp9_a3_llm is not None:
        for macro_prefix, model_id in (
            ("Qwen", "Qwen/Qwen2.5-0.5B"),
            ("Llama", "meta-llama/Llama-3.2-1B"),
        ):
            entry = exp9_a3_llm[model_id]
            macros[f"Phi{macro_prefix}"] = round_str(entry["phi"]["mean"], 3)
            sizes = _group_sizes(
                exp9_a3_llm, "exp9_a3_llm", model_id, entry["seeds"].values()
            )
            if sizes is not None:
                macros[f"PhiNull{macro_prefix}"] = round_str(phi_null(sizes), 3)

    # --- Phi-map cell count (mirrors the rows tab:phi-map prints) -----------------
    # Count cells in the available bundles and reconcile the weight-state counts.
    n_total = 0
    for bundle in (exp8, exp8_a1_width, exp8_a1_imagenet32, exp8_a2):
        if bundle is not None:
            n_total += sum(len(checkpoints) for _, checkpoints in data_items(bundle))
    for bundle in (exp9, exp9_a3_llm):
        if bundle is not None:
            n_total += len(data_items(bundle))
    macros["PhiCellsTotal"] = round_str(float(n_total), 0)
    # Count weight states only when all bundles for the map are present.
    if (
        exp8_a1_width is not None
        and exp8_a1_imagenet32 is not None
        and exp8_a2 is not None
        and exp9_a3_llm is not None
    ):
        counts = _phi_cells_by_weight_state(
            exp8,
            exp8_a1_width,
            exp8_a1_imagenet32,
            exp8_a2,
            exp9,
            exp9_a3_llm,
        )
        n_classified = counts.trained + counts.random_init + counts.pretrained_body
        if n_classified != n_total:
            raise ValueError(
                "PhiCellsTotal: the manuscript says the map has PhiCellsTotal cells, "
                "PhiCellsTrainedWeights of them with trained weights, "
                "PhiCellsRandomInit with random weights and one with a pretrained body "
                f"under a new head, but the map has {n_total} cells and the three "
                f"classes count {counts.trained} + {counts.random_init} + "
                f"{counts.pretrained_body} = {n_classified}; the passage must change "
                "with it"
            )
        macros["PhiCellsTrainedWeights"] = round_str(float(counts.trained), 0)
        macros["PhiCellsTrainedBelowSep"] = round_str(
            float(counts.trained_below_sep), 0
        )
        macros["PhiCellsRandomInit"] = round_str(float(counts.random_init), 0)
        macros["PhiCellsCnnMidFinal"] = round_str(float(counts.cnn_mid_final), 0)
        macros["PhiCellsCnnBetweenReferences"] = round_str(
            float(counts.cnn_between_references), 0
        )

    # --- gate A, pooled over the pre-registered run and its replication ----------
    if exp8_a1_v2 is not None:
        replicated = gate_a_replicated([exp8, exp8_a1_v2], checkpoint="final")
        if not replicated["missing"]:
            macros["GateASeedLo"] = round_str(replicated["ci_low_seeds"], 3)
            macros["GateASeedHi"] = round_str(replicated["ci_high_seeds"], 3)

        # Same pooled construction, one checkpoint earlier: the six values (2 runs
        # x 3 seeds) at the middle checkpoint.
        replicated_mid = gate_a_replicated([exp8, exp8_a1_v2], checkpoint="mid")
        if not replicated_mid["missing"]:
            macros["GateAMidPooledMean"] = round_str(replicated_mid["mean"], 3)
            macros["GateAMidPooledLo"] = round_str(replicated_mid["ci_low"], 3)
            macros["GateAMidPooledHi"] = round_str(replicated_mid["ci_high"], 3)

        # Check the middle-checkpoint differences in the optional replication.
        replication_mid = gate_a(exp8_a1_v2, checkpoint="mid")
        if not all(delta > 0.0 for delta in replication_mid["delta"].values()):
            raise ValueError(
                "GateAMidPooledMean: Section 4.1 states the middle-checkpoint "
                "difference Phi_ResNet - Phi_Plain is positive on every seed of "
                "the CIFAR-100 replication as well, but exp8_a1_v2's per-seed "
                f"deltas are {replication_mid['delta']!r}"
            )

    # --- accuracy-matched replication on the long, 300-epoch schedule ------------
    if exp8_a1_long is not None:
        matched = accuracy_matched_delta_phi(exp8_a1_long)
        macros["LongDeltaPhi"] = round_str(matched["mean"], 3)
        macros["LongDeltaPhiLo"] = round_str(matched["ci_low"], 3)
        macros["LongDeltaPhiHi"] = round_str(matched["ci_high"], 3)
        macros["LongPairs"] = round_str(float(matched["n_pairs"]), 0)

        # Sweep the same pairing rule over tolerances including the working value.
        sweep_means: dict[float, float] = {}
        for tol in _LONG_TOL_SWEEP:
            swept = accuracy_matched_delta_phi(exp8_a1_long, tol=tol)
            if swept["n_seeds"] < 2:
                raise ValueError(
                    "LongDeltaPhiTolLo/LongDeltaPhiTolHi: accuracy_matched_delta_phi "
                    f"at tol={tol!r} keeps pairs for only {swept['n_seeds']} seed(s); "
                    "the long-schedule tolerance sweep needs at least two seeds with a kept "
                    "pair at every grid point to report a mean and an interval"
                )
            sweep_means[tol] = swept["mean"]

        if _LONG_TOL not in sweep_means:
            raise ValueError(
                "LongDeltaPhiTolLo/LongDeltaPhiTolHi: the working tolerance "
                f"{_LONG_TOL!r} (tables.exp789._LONG_TOL) is not one of the swept "
                f"values {sorted(sweep_means)}"
            )

        macros["LongTolWorking"] = round_str(_LONG_TOL, 3)
        macros["LongTolLo"] = round_str(min(_LONG_TOL_SWEEP), 3)
        macros["LongTolHi"] = round_str(max(_LONG_TOL_SWEEP), 3)
        macros["LongDeltaPhiTolLo"] = round_str(min(sweep_means.values()), 3)
        macros["LongDeltaPhiTolHi"] = round_str(max(sweep_means.values()), 3)

        # The reported mean remains positive over the sweep.
        if any(mean <= 0.0 for mean in sweep_means.values()):
            raise ValueError(
                "LongDeltaPhiTolLo/LongDeltaPhiTolHi: the manuscript states that the sign of the "
                "accuracy-matched mean does not change over the tolerance sweep, "
                f"but the swept means {sweep_means!r} include a non-positive value"
            )

        long_resnet = exp8_a1_long["resnet18"]["final"]
        long_plain = exp8_a1_long["plain_resnet18"]["final"]
        long_resnet_phi = mean_std(
            [_phi_by_probes(p, _LONG_PROBES) for p in long_resnet["seeds"].values()]
        )["mean"]
        macros["LongPhiResnetFinal"] = round_str(long_resnet_phi, 3)
        macros["LongAccResnetFinal"] = round_str(
            as_percent(long_resnet["test_acc_mean"]), 1
        )
        macros["LongAccPlainFinal"] = round_str(
            as_percent(long_plain["test_acc_mean"]), 1
        )

    # --- granularity of the partition, three levels, one consistent measurement
    # (exp8_a2_gran_v3, on demand): it carries diag_frob at every level, so Phi,
    # Phi_sep and S at the three partitions come from one draw.
    # The VThree suffix spells out the digit for a valid LaTeX control sequence.
    if exp8_a2_gran_v3 is not None:
        gran_seeds = list(exp8_a2_gran_v3["resnet50"]["init"]["seeds"].values())
        gran = {level: _granularity_stats(gran_seeds, level) for level in LEVELS}

        macros["GranGroupsStage"] = round_str(gran["stage"]["n_groups"], 0)
        macros["GranGroupsBlock"] = round_str(gran["block"]["n_groups"], 0)
        macros["GranGroupsLayer"] = round_str(gran["layer"]["n_groups"], 0)

        macros["PhiGranStageVThree"] = round_str(gran["stage"]["phi"], 3)
        macros["PhiGranBlockVThree"] = round_str(gran["block"]["phi"], 3)
        # Four decimals, not the usual three: PhiGranLayer's own trap above -- at
        # three this value rounds to 1.000, misreading as complete decoupling.
        macros["PhiGranLayerVThree"] = round_str(gran["layer"]["phi"], 4)

        macros["PhiSepGranStage"] = round_str(gran["stage"]["sep"], 3)
        macros["PhiSepGranBlock"] = round_str(gran["block"]["sep"], 3)
        macros["PhiSepGranLayer"] = round_str(gran["layer"]["sep"], 3)

        macros["SGranStage"] = round_str(gran["stage"]["s"], 3)
        macros["SGranBlock"] = round_str(gran["block"]["s"], 3)
        macros["SGranLayer"] = round_str(gran["layer"]["s"], 3)

        macros["OffOverSepGranStage"] = round_str(gran["stage"]["off"], 1)
        macros["OffOverSepGranBlock"] = round_str(gran["block"]["off"], 1)
        macros["OffOverSepGranLayer"] = round_str(gran["layer"]["off"], 0)

        # 1 - Phi, rounded once from the raw mean -- never from an already-rounded
        # PhiGranStageVThree/PhiGranLayerVThree.
        macros["KeptShareStage"] = round_str(1.0 - gran["stage"]["phi"], 3)
        macros["KeptShareLayer"] = round_str(1.0 - gran["layer"]["phi"], 4)
        # Retained estimand: ratios of seed means of Phi, NOT means of
        # per-seed ratios. These two shares sum to 100 before rounding.
        macros["DiscardedBetweenStages"] = round_str(
            100 * gran["stage"]["phi"] / gran["layer"]["phi"], 1
        )
        macros["DiscardedWithinStages"] = round_str(
            100 * (gran["layer"]["phi"] - gran["stage"]["phi"]) / gran["layer"]["phi"],
            1,
        )

        # `Regrouped`'s block
        # and layer levels are not nestings of the six-group partition -- everything
        # outside a level's leaf classes is pooled into one "rest" group, and "rest"
        # spans more than one stage at both finer levels -- so monotonicity does not
        # by itself cover either one. The two macros below are the evidence section 3 states
        # for the two levels: the layer level's "rest" block is negligible, so Phi
        # there is a lower bound anyway (RestMassLayerPpm); the block level's "rest"
        # is stem-and-head, so it is not a refinement at all and Phi can (and on one
        # seed, does) fall going from six groups to seventeen
        # (PhiBlockBelowStageSeeds): their mutual block, off the diagonal part at six
        # groups, is on it at seventeen. ||H_theta||_F^2 is not recorded directly;
        # RestMassLayerPpm
        # recovers it from the same diagonal-mass identity `_off_over_sep` already
        # uses elsewhere in this module: sum_v a_v^2 / (1 - Phi) = ||H||_F^2, at the
        # layer granularity.

        # RestMassLayerPpm: the layer partition's own "rest" group (the BatchNorm
        # affines of five of the six stages) contributes only its own diagonal
        # block, a_rest^2, to ||H||_F^2 at that level; since splitting "rest" further
        # can only move mass from that diagonal block to some off-diagonal one (by
        # the same monotonicity argument section 3 states), this bounds the whole
        # discrepancy a genuinely nested per-module layer partition could show
        # relative to the measured one. Parts per million of ||H_theta||_F^2, one
        # decimal: it is the number that lets section 3 call the layer value a lower bound
        # in spite of "rest" not being a leaf module.
        rest_ppms = [
            1e6
            * p["diag_frob_by_granularity"]["layer"]["rest"] ** 2
            / (
                sum(v * v for v in p["diag_frob_by_granularity"]["layer"].values())
                / (1.0 - p["phi_by_granularity"]["layer"])
            )
            for p in gran_seeds
        ]
        macros["RestMassLayerPpm"] = round_str(sum(rest_ppms) / len(rest_ppms), 1)

        # PhiBlockBelowStageSeeds: how many of the three seeds have
        # phi_by_granularity["block"] < phi (the six-group value) -- the direct,
        # per-seed check that the block level is not a refinement, since the
        # seed-mean PhiGranBlockVThree/PhiGranStageVThree pair above (0.928 vs.
        # 0.927) hides that on one seed the "refined" value is the lower one. A
        # plain count, zero decimals.
        macros["PhiBlockBelowStageSeeds"] = round_str(
            float(
                sum(
                    1 for p in gran_seeds if p["phi_by_granularity"]["block"] < p["phi"]
                )
            ),
            0,
        )

    # --- CIFAR granularity, six groups vs. the layer partition (on demand):
    # exp8_a1_long_gran_m3000, re-measured at n_probes=3000 from exp8_a1_long's own
    # published final checkpoints (--restore-checkpoints-dir) -- so the six test_acc
    # values reproduce exp8_a1_long's exactly (test_paper_data_numbers.py's fingerprint
    # test) and this is the same weights, a second Hutchinson draw, not a retraining
    # run. "Final..." names this
    # final-checkpoint-only family; "Long..." above stays reserved for the
    # accuracy-matched family over exp8_a1_long's full schedule -- a different
    # quantity.
    if exp8_a1_long_gran_m3000 is not None:
        # The inversion, decomposed, at both partitions: paired by seed (the two
        # architectures share their three seeds), then the t-interval over the
        # three per-seed differences, through _paired_seed_deltas and _t_interval.
        for level, level_macro in (("stage", "Stage"), ("layer", "Layer")):
            deltas = _paired_seed_deltas(exp8_a1_long_gran_m3000, level)
            for quantity, values in deltas.items():
                interval = _t_interval(values)
                name = f"FinalDelta{quantity}{level_macro}"
                macros[name] = round_str(interval["mean"], 4)
                macros[f"{name}Lo"] = round_str(interval["ci_low"], 4)
                macros[f"{name}Hi"] = round_str(interval["ci_high"], 4)

    return macros


