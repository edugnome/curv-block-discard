def num_b(
    exp7: dict[str, Any],
    exp8: dict[str, Any],
    exp8_a1_width: dict[str, Any] | None,
    exp8_a1_imagenet32: dict[str, Any] | None,
    exp8_a2: dict[str, Any] | None,
    exp9: dict[str, Any],
    exp9_a3_llm: dict[str, Any] | None,
    exp8_a1_v2: dict[str, Any] | None,
    exp8_a1_long: dict[str, Any] | None,
    exp11: dict[str, Any] | None,
    exp11_sgd: dict[str, Any],
    exp11_adam: dict[str, Any],
    exp8_a2_gran_v3: dict[str, Any] | None,
    exp8_a1_long_gran_m3000: dict[str, Any] | None,
    exp11_kfac_seam: dict[str, Any] | None,
) -> str:
    r"""The manuscript's inline numbers (``num:b``), as ``\newcommand`` definitions.

    One line per macro, ``\newcommand{\<Name>}{<value>}``, sorted by name under a
    generated-file header comment. `_stage_a`, `_stage_b` and `_validity` each
    return one dict of macro name -> pre-formatted value; `_merge` unions them and
    raises ``ValueError`` naming the key on a collision, since a name produced by two
    of the three groups would otherwise pick a value silently.

    The parameter names above are exactly `paper_data.registry.REGISTRY`'s bundle
    list for ``"num:b"``, in that order
    (``test_every_generator_takes_its_registry_bundles_in_order``): this is the
    public, registered generator, not `_stage_a`'s own convenience names.
    """
    macros = _merge(
        _stage_a(
            exp8,
            exp8_a1_width,
            exp8_a1_imagenet32,
            exp8_a2,
            exp9,
            exp9_a3_llm,
            exp8_a1_v2,
            exp8_a1_long,
            exp8_a2_gran_v3,
            exp8_a1_long_gran_m3000,
        ),
        _stage_b(exp7),
        _validity(exp11, exp11_sgd, exp11_adam, exp11_kfac_seam),
    )
    lines = [
        rf"\newcommand{{\{name}}}{{{value}}}" for name, value in sorted(macros.items())
    ]
    return "\n".join([_HEADER, *lines])
