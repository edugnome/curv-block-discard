def _tstar_at(bundle: dict[str, Any], steps: tuple[int, ...]) -> list[float]:
    """t* over every (seed, step) cell of ``bundle`` whose step is in ``steps``."""
    return [
        float(probe["t_star"])
        for payload in bundle["seeds"].values()
        for probe in payload["probes"]
        if int(probe["step"]) in steps
    ]


def _count_at_most(
    bundles: Sequence[dict[str, Any]], threshold: float, from_step: int
) -> tuple[int, int]:
    """(cells at or below ``threshold``, cells counted) over arm x seed x step, for
    steps at or after ``from_step``; a NaN t* (no grid point met the tolerance) is
    dropped from both, neither a satisfied cell nor a violation.

    Mirrors `paper_data.tables.exp11._count_at_most` (private to that table, so
    repeated here rather than imported) minus its third return value, the count of
    dropped NaN cells, which has no macro of its own.
    """
    satisfied = counted = 0
    for bundle in bundles:
        for payload in bundle["seeds"].values():
            for probe in payload["probes"]:
                if int(probe["step"]) < from_step:
                    continue
                t_star = float(probe["t_star"])
                if math.isnan(t_star):
                    continue
                counted += 1
                if t_star <= threshold:
                    satisfied += 1
    return satisfied, counted


def _curv_along_d0(probe: dict[str, Any]) -> float:
    return float(probe["sharpness"]["curv_along_d0"])


def _kappa_sec(probe: dict[str, Any]) -> float:
    """The secant curvature at t = 1 per unit ||d0||^2, for one probe's own record.

    Formed per seed, before any seed reduction (`paper_data.tables.exp11`'s own
    caution: do not divide a mean secant by a mean ||d0||^2).
    """
    at_one = next(
        (p for p in probe["curve_d0"] if math.isclose(float(p["t"]), 1.0)), None
    )
    if at_one is None:
        return math.nan
    norm_d0 = float(probe["decomposition"]["norm_d0"])
    return float(at_one["secant"]) / norm_d0**2


def _kink_frac(probe: dict[str, Any]) -> float:
    row = next(
        (r for r in probe["kinks"]["rows"] if math.isclose(float(r["t"]), 1.0)), None
    )
    return float(row["relu_frac"]) if row else math.nan


def _probe_at(payload: dict[str, Any], step: int) -> dict[str, Any]:
    return next(p for p in payload["probes"] if int(p["step"]) == step)


# --- D0.1: the two curvatures, every probe of the three arms and three seeds ------

_CURV_RATIO_MIN_STEP = 60


def _cell_curvatures(
    bundle: dict[str, Any], arm_name: str
) -> list[tuple[int, float, float]]:
    """(step, pointwise, secant) for every (seed, step) cell of one arm ``bundle``.

    Pointwise is `_curv_along_d0` (``curv_along_d0``, already ``d0'Hd0/||d0||^2``);
    secant is `_kappa_sec` at t = 1 (``tables.exp11._kappa_sec``'s own seam, already
    per unit ||d0||^2 too) -- reused, not reimplemented. A cell with no t = 1 point
    in its ``curve_d0`` (`_kappa_sec` returning NaN) is a hard failure naming the arm,
    seed and step.
    """
    cells: list[tuple[int, float, float]] = []
    for seed, payload in bundle["seeds"].items():
        for probe in payload["probes"]:
            secant = _kappa_sec(probe)
            if math.isnan(secant):
                raise ValueError(
                    f"{arm_name} seed {seed} step {probe['step']}: curve_d0 has no "
                    "t=1 point (_kappa_sec is NaN)"
                )
            cells.append((int(probe["step"]), _curv_along_d0(probe), secant))
    return cells


def _curv_ratio_cancellation_holds(probe: dict[str, Any]) -> bool:
    """True iff pointwise/secant computed through `_curv_along_d0`/`_kappa_sec`
    (both already divided by ||d0||^2) agrees with the same ratio formed from the
    two raw, unnormalised fields (``d0_H_d0`` and ``curve_d0``'s own ``secant`` at
    t = 1), checking cancellation of the ||d0||^2 factor."""
    at_one = next(p for p in probe["curve_d0"] if math.isclose(float(p["t"]), 1.0))
    raw_ratio = float(probe["decomposition"]["d0_H_d0"]) / float(at_one["secant"])
    normalised_ratio = _curv_along_d0(probe) / _kappa_sec(probe)
    return math.isclose(raw_ratio, normalised_ratio, rel_tol=1e-9)


# --- D0.2: t*'s sensitivity to the tolerance ---------------------------------------


def _bundle_tolerance(arms: Sequence[dict[str, Any]]) -> float:
    """The relative tolerance every arm bundle was actually measured at, read from
    each bundle's own ``meta``  -- not
    typed as a literal, for the same reason `Exp7Config.tau` backs `CouplingBelowTau`
    rather than a hardcoded threshold: a changed protocol tolerance must change this
    macro (and, downstream, Appendix B's own statement of it) rather than silently
    falsify it. Raises ``ValueError`` naming the values if the arms disagree.
    """
    values = {float(bundle["meta"]["tolerance"]) for bundle in arms}
    if len(values) != 1:
        raise ValueError(f"arms disagree on the configured tolerance: {sorted(values)}")
    return next(iter(values))


def _tstar_sweep(
    arms: Sequence[dict[str, Any]], tolerance: float, from_step: int
) -> list[float]:
    """t* of every (arm, seed, step) cell at or after ``from_step``, recomputed at
    ``tolerance`` from each cell's own stored ``curve_d0`` points via
    `experiments.runner_exp11.validity_radius` -- the paper's own definition
    (including its prefix rule), re-evaluated rather than reimplemented.
    NaN means the tolerance already fails at the smallest grid point
    (`validity_radius`'s own convention: below the grid).
    """
    return [
        validity_radius(probe["curve_d0"], tolerance)
        for bundle in arms
        for payload in bundle["seeds"].values()
        for probe in payload["probes"]
        if int(probe["step"]) >= from_step
    ]


def _tstar_ok_and_median(
    t_stars: Sequence[float], threshold: float
) -> tuple[int, float]:
    """(cells with t* <= ``threshold``, median t* over the cells whose radius lies on
    the grid): a cell
    whose radius is below the grid *satisfies* t* <= threshold (its radius is smaller
    than every grid point, hence smaller than ``threshold`` too), so it is counted in
    the first return value but excluded, with every other cell without a radius, from
    the median (over on-grid cells only) -- never replaced by zero, never dropped from
    the count.

    A cell without a radius is NaN here whether it is below the grid or undetermined
    (`_is_undetermined`); the count is exact only where there is none of the
    second kind, which `_undetermined_macros` makes a precondition at 0.2 and 0.5. At
    0.05, where there are two, only the median is read: it excludes both kinds alike.
    """
    ok = sum(1 for t in t_stars if math.isnan(t) or t <= threshold)
    on_grid = [t for t in t_stars if not math.isnan(t)]
    median = statistics.median(on_grid) if on_grid else math.nan
    return ok, median


# --- t* of the model without its damping term -------------------------------------

# The two reporting thresholds on t* the undamped-radius counts use, and the first probe
# step they count from: "at most a tenth of the step", "at least half of the step", from
# step 200 on -- the population `_count_at_most(arms, 0.1, 200)` gives TstarCellsOk. Like
# that 0.1, the first is a threshold on t* itself and not TstarTol, the relative
# tolerance inside its definition; the two are numerically equal and independent.
_TSTAR_AT_MOST = 0.1
_TSTAR_AT_LEAST = 0.5
_TSTAR_FROM_STEP = 200


def _model_radius(probe: dict[str, Any], tolerance: float, *, damped: bool) -> float:
    """t* of one probe's model along d0, recomputed from its stored ``curve_d0``.

    The model is m(t) = t g.d + t^2/2 (d.Hd + lambda ||d||^2), the stored ``m`` of each
    grid point (`experiments.runner_exp11.model_curve`). ``damped=True`` uses it as it
    is; ``damped=False`` takes the damping term t^2/2 lambda ||d||^2 out of it, with
    ``decomposition.lambda_norm_d0_sq`` = lambda ||d0||^2 as the runner stores it. Both
    go through one path -- the runner's own relative error (`_rel_err`) against the
    stored ``dL``, then its own prefix rule (`validity_radius`), the same tolerance --
    so the damped call, which must give back the stored ``t_star`` (`_undamped_validity`
    checks that on every probe), is what makes the undamped one a statement about the
    runner's definition and not about a second one.
    """
    lambda_norm_sq = (
        0.0 if damped else float(probe["decomposition"]["lambda_norm_d0_sq"])
    )
    points = [
        {
            "t": float(point["t"]),
            "rel_err": _rel_err(
                float(point["dL"]),
                float(point["m"]) - 0.5 * float(point["t"]) ** 2 * lambda_norm_sq,
            ),
        }
        for point in probe["curve_d0"]
    ]
    return validity_radius(points, tolerance)


def _undamped_validity(
    exp11: dict[str, Any],
    exp11_sgd: dict[str, Any],
    exp11_adam: dict[str, Any],
) -> dict[str, str]:
    """``TstarUndampedOkKfac``, ``TstarUndampedOkSgd``, ``TstarUndampedHalfAdam``,
    ``TstarCellsPerArm`` and ``DampSharePctAdamLo``/``DampSharePctAdamHi``.

    For each cell at step ``_TSTAR_FROM_STEP`` or later, t* is computed for the
    model with its damping term removed (`_model_radius`):
    the number of K-FAC cells and of SGD cells whose t* is at most ``_TSTAR_AT_MOST`` of
    the step, the number of Adam cells whose t* is at least ``_TSTAR_AT_LEAST`` of it,
    and the cells per arm those counts are out of. ``DampSharePctAdamLo``/``Hi`` are the
    smallest and largest, over the Adam cells, of the damping term's share of the
    model's quadratic coefficient, lambda ||d0||^2 / (d0.H.d0 + lambda ||d0||^2), in
    percent.

    Four preconditions, each a ``ValueError`` naming the macros and what the text would
    have to change:

    - on every probe of the three bundles (every step, not only the cells counted) the
      damped model's t*, recomputed from the stored ``dL`` and ``m`` by the same path,
      equals the stored ``t_star`` (two NaNs count as equal): the recomputation repeats
      the runner's rule;
    - no undamped t* is NaN. `_count_at_most` (TstarCellsOk) drops a NaN t* from
      numerator and denominator alike; here that would change the denominator
      TstarCellsPerArm stands for, and a NaN reads opposite ways against the two
      thresholds (below the grid satisfies "at most", not "at least"). NaNs are
      therefore rejected;
    - the three arms hold the same number of cells;
    - ``d0_H_d0`` >= 0 on the Adam cells, without which the ratio above is not a share.
    """
    arms = (("Kfac", exp11), ("Sgd", exp11_sgd), ("Adam", exp11_adam))
    tolerance = _bundle_tolerance([bundle for _, bundle in arms])
    radii: dict[str, list[float]] = {}
    shares: list[float] = []
    for arm, bundle in arms:
        radii[arm] = []
        for seed, payload in bundle["seeds"].items():
            for probe in payload["probes"]:
                step = int(probe["step"])
                where = f"{arm} seed {seed} step {step}"
                stored = float(probe["t_star"])
                damped = _model_radius(probe, tolerance, damped=True)
                if not (
                    damped == stored or (math.isnan(damped) and math.isnan(stored))
                ):
                    raise ValueError(
                        "TstarUndampedOkKfac/TstarUndampedOkSgd/TstarUndampedHalfAdam: "
                        f"recomputing t* of the damped model from the stored dL and m "
                        f"gives {damped!r} on {where}, but the bundle stores t_star="
                        f"{stored!r}; the recomputation does not repeat the runner's "
                        "rule, so a t* computed the same way without the damping term "
                        "cannot be trusted"
                    )
                if step < _TSTAR_FROM_STEP:
                    continue
                undamped = _model_radius(probe, tolerance, damped=False)
                if math.isnan(undamped):
                    raise ValueError(
                        "TstarUndampedOkKfac/TstarUndampedOkSgd/TstarUndampedHalfAdam: "
                        f"t* without the damping term is NaN on {where} (the model is "
                        "outside the tolerance at the first grid point); the convention "
                        "of TstarCellsOk drops a NaN from numerator and denominator "
                        "alike, which would make TstarCellsPerArm the wrong denominator "
                        "of these counts, so the convention has to be decided here"
                    )
                radii[arm].append(undamped)
                if arm == "Adam":
                    decomposition = probe["decomposition"]
                    d_h_d = float(decomposition["d0_H_d0"])
                    lambda_norm_sq = float(decomposition["lambda_norm_d0_sq"])
                    if d_h_d < 0.0:
                        raise ValueError(
                            "DampSharePctAdamLo/DampSharePctAdamHi: d0_H_d0 is "
                            f"{d_h_d!r} on {where}; lambda ||d0||^2 / (d0.H.d0 + "
                            "lambda ||d0||^2) is then not the damping term's share of "
                            "the quadratic coefficient"
                        )
                    shares.append(lambda_norm_sq / (d_h_d + lambda_norm_sq))

    cells_per_arm = {arm: len(values) for arm, values in radii.items()}
    if len(set(cells_per_arm.values())) != 1:
        raise ValueError(
            "TstarCellsPerArm: the arms hold different numbers of cells at step "
            f">= {_TSTAR_FROM_STEP}: {cells_per_arm!r}; one macro cannot be the "
            "denominator of all three counts"
        )
    return {
        "TstarCellsPerArm": round_str(float(cells_per_arm["Kfac"]), 0),
        "TstarUndampedOkKfac": round_str(
            float(sum(1 for t in radii["Kfac"] if t <= _TSTAR_AT_MOST)), 0
        ),
        "TstarUndampedOkSgd": round_str(
            float(sum(1 for t in radii["Sgd"] if t <= _TSTAR_AT_MOST)), 0
        ),
        "TstarUndampedHalfAdam": round_str(
            float(sum(1 for t in radii["Adam"] if t >= _TSTAR_AT_LEAST)), 0
        ),
        "DampSharePctAdamLo": round_str(100 * min(shares), 0),
        "DampSharePctAdamHi": round_str(100 * max(shares), 0),
    }


# --- A cell failing at the smallest grid point on noise is undetermined ------------


class _TstarCell(NamedTuple):
    """One arm x seed x probe step cell of the t* grid, at one tolerance."""

    where: str  # "Kfac seed seed_43 step 1500", for a message
    t_star: float  # `validity_radius` on the stored errors; NaN: no radius
    first: float  # the model's stored relative error at the grid's first point
    second: float  # ... at its second point


def _tstar_cells(
    arm_bundles: Mapping[str, dict[str, Any]], tolerance: float, from_step: int
) -> list[_TstarCell]:
    """Every cell at step ``from_step`` or later, in `_tstar_sweep`'s order, its radius
    recomputed at ``tolerance`` from the stored ``curve_d0`` errors by the runner's own
    rule (`validity_radius`), with the errors at the grid's first two points beside it.
    """
    return [
        _TstarCell(
            f"{arm} seed {seed} step {probe['step']}",
            validity_radius(probe["curve_d0"], tolerance),
            float(probe["curve_d0"][0]["rel_err"]),
            float(probe["curve_d0"][1]["rel_err"]),
        )
        for arm, bundle in arm_bundles.items()
        for seed, payload in bundle["seeds"].items()
        for probe in payload["probes"]
        if int(probe["step"]) >= from_step
    ]


def _is_undetermined(cell: _TstarCell, tolerance: float) -> bool:
    """A cell without a radius whose error at the *second* grid point fits ``tolerance``.

    `validity_radius` returns NaN when the first grid point already fails; Appendix B
    reads that as "the radius is below the grid". It is that only if the model's error is
    still large one point up. When the error is within the tolerance at the second point
    and outside it at the first, the model's smooth error is not what failed there: a
    Taylor remainder falls as t falls, relatively and (cubically) absolutely, and here
    both are larger at t = 1e-4 than at 1e-3 (pinned on the three cells that have it in
    `test_paper_data_numbers`). The author reads the first point as noise in the loss
    difference; this function asserts only
    what the stored errors show. Such a cell is undetermined. Any other cell without a
    radius is below the grid.
    """
    return math.isnan(cell.t_star) and cell.second <= tolerance


def _undetermined_macros(
    arm_bundles: Mapping[str, dict[str, Any]], reported: float
) -> dict[str, str]:
    """``TstarUndeterminedTolFive``, ``TstarCellsDefinedTolFive`` and
    ``TstarCellsOkDefinedTolFive``.

    The tolerance sweep of D0.2 counts a cell without a radius as satisfying
    t* <= 0.1 (`_tstar_ok_and_median`: its radius is below the grid). At a tolerance of
    0.05 two K-FAC cells (seeds 43 and 44, step 1500) have no radius, and both are
    undetermined, not below the grid (`_is_undetermined`). The three macros are the count
    of such cells, the count of the others, and how many of those are at most a tenth of
    the step. They replace ``TstarCellsOkTolFive`` and ``TstarBelowGridTolFive``, which
    counted the two cells as satisfying and as below the grid and which the text no longer
    cites.

    Preconditions, each a ``ValueError`` naming the macro (the writing rule: an absolute
    word in the prose needs a precondition here):
      - an undetermined cell's error falls from the first grid point to the second: the
        text calls the cell noise in the loss difference because the error falls fifty-
        to a hundredfold, so the second error must be below the first (only the direction
        is checked here: the fold itself stands in the prose without a macro);
      - no cell is undetermined at any other tolerance the generator counts a NaN cell
        at (0.5 and 0.2 of the sweep, and the reported ``reported``): those macros count
        such a cell as satisfying (the sweep) or drop it (`_count_at_most`) without
        saying so, and none of them has an undetermined-aware count beside it.
    """
    tolerance = 0.05
    cells = _tstar_cells(arm_bundles, tolerance, _TSTAR_FROM_STEP)
    flags = [_is_undetermined(cell, tolerance) for cell in cells]
    for cell, undetermined in zip(cells, flags, strict=True):
        if undetermined and not cell.second < cell.first:
            raise ValueError(
                f"TstarUndeterminedTolFive: {cell.where} is counted undetermined "
                f"because its error at the second grid point ({cell.second:.2g}) fits "
                f"the tolerance {tolerance:g}, but that error is not below its error at "
                f"the first ({cell.first:.2g}); the text calls such a cell noise in the "
                "loss difference, an error that falls by orders of magnitude, so the "
                "sentence must change with it"
            )
    for other, macro in (
        (0.5, "TstarCellsOkTolFifty"),
        (0.2, "TstarCellsOkTolTwenty"),
        (reported, "TstarCellsOk"),
    ):
        for cell in _tstar_cells(arm_bundles, other, _TSTAR_FROM_STEP):
            if _is_undetermined(cell, other):
                raise ValueError(
                    f"{macro}: {cell.where} has no radius at the tolerance {other:g} "
                    f"and its error at the second grid point ({cell.second:.2g}) fits "
                    "it, so it is undetermined, not below the grid; this macro does not "
                    "tell the two apart, so it needs an undetermined-aware count beside "
                    "TstarUndeterminedTolFive and the sentence that cites it must say so"
                )
    defined = [
        c for c, undetermined in zip(cells, flags, strict=True) if not undetermined
    ]
    ok = sum(1 for c in defined if math.isnan(c.t_star) or c.t_star <= _TSTAR_AT_MOST)
    return {
        "TstarUndeterminedTolFive": round_str(float(sum(flags)), 0),
        "TstarCellsDefinedTolFive": round_str(float(len(defined)), 0),
        "TstarCellsOkDefinedTolFive": round_str(float(ok), 0),
    }


# --- Replicate of the K-FAC run of seed 42 -----------------------------------------


def _replicate_macros(
    original: dict[str, Any], replicate: dict[str, Any]
) -> dict[str, str]:
    """``TstarReplicateStepTwoHundred``/``SixHundred``,
    ``TstarOriginalStepTwoHundred``/``SixHundred`` and ``TstarReplicateUndeterminedStep``.

    The K-FAC run of seed 42 repeated (``results/exp11_kfac_seam``: one seed, the same
    grid, tolerance and probe steps) against the run of the same seed in the three-seed
    design: t* at steps 200 and 600 in both, and the step of the replicate's one cell
    that has no radius. Stored ``t_star`` throughout, the value the runner wrote.

    Preconditions, each a ``ValueError`` naming the macro and the sentence:
      - the runs are comparable: the replicate holds seed_42 only, and it and the
        original agree on tolerance, grid and probe steps;
      - the replicate crosses a tenth of the step at step 200 (``t*`` above
        ``_TSTAR_AT_MOST``) where the original stays within it;
      - exactly one replicate cell has no radius, and it is undetermined
        (`_is_undetermined`) with an error that falls from the first grid point to the
        second: the text calls it a failure on noise at the smallest grid point (only the
        direction of the fall is checked here).
    """
    seeds = list(replicate["seeds"])
    if seeds != ["seed_42"] or "seed_42" not in original["seeds"]:
        raise ValueError(
            "TstarReplicateStepTwoHundred: the text compares the K-FAC run of seed 42 "
            f"with its replicate, seed_42 only, but the replicate holds {seeds} and the "
            "original "
            f"{list(original['seeds'])}; the sentence must change with it"
        )
    for key in ("tolerance", "t_grid", "probe_steps"):
        if replicate["meta"][key] != original["meta"][key]:
            raise ValueError(
                "TstarReplicateStepTwoHundred: the replicate and the original differ in "
                f"{key} ({replicate['meta'][key]!r} against {original['meta'][key]!r}), so "
                "their radii are not one measurement repeated; the sentence must "
                "change with it"
            )

    def by_step(bundle: dict[str, Any]) -> dict[int, dict[str, Any]]:
        return {int(p["step"]): p for p in bundle["seeds"]["seed_42"]["probes"]}

    rep, orig = by_step(replicate), by_step(original)
    radius = {
        (name, step): float(probe[step]["t_star"])
        for name, probe in (("replicate", rep), ("original", orig))
        for step in (200, 600)
    }
    if not radius["replicate", 200] > _TSTAR_AT_MOST >= radius["original", 200]:
        raise ValueError(
            "TstarReplicateStepTwoHundred/TstarOriginalStepTwoHundred: the text says "
            "the replicate crosses a tenth of the step at step 200 where the original "
            "run stays "
            f"within it, but t* is {radius['replicate', 200]:g} in the replicate and "
            f"{radius['original', 200]:g} in the original; the sentence must change "
            "with it"
        )
    no_radius = [p for p in rep.values() if math.isnan(float(p["t_star"]))]
    if len(no_radius) != 1:
        raise ValueError(
            "TstarReplicateUndeterminedStep: the text names the one cell of the "
            f"replicate without a radius, but it has {len(no_radius)} cells without a "
            f"radius ({[int(p['step']) for p in no_radius]}); the sentence must change "
            "with it"
        )
    probe = no_radius[0]
    step = int(probe["step"])
    tolerance = float(replicate["meta"]["tolerance"])
    first, second = (float(probe["curve_d0"][i]["rel_err"]) for i in (0, 1))
    if not second <= tolerance:
        raise ValueError(
            f"TstarReplicateUndeterminedStep: the replicate's cell without a radius is "
            f"at step {step} and the text calls it undetermined, but its error at the "
            f"second grid point ({second:.2g}) is above the tolerance {tolerance:g}, so "
            "it is not undetermined but below the grid; the sentence must change with it"
        )
    if not second < first:
        raise ValueError(
            f"TstarReplicateUndeterminedStep: the replicate's cell at step {step} is "
            "undetermined by its error at the second grid point "
            f"({second:.2g}), but that is not below its error at the first ({first:.2g}); "
            "the text calls it a failure on noise, an error that falls by orders of "
            "magnitude, so the sentence must change with it"
        )
    return {
        "TstarReplicateStepTwoHundred": exact_str(radius["replicate", 200]),
        "TstarOriginalStepTwoHundred": exact_str(radius["original", 200]),
        "TstarReplicateStepSixHundred": exact_str(radius["replicate", 600]),
        "TstarOriginalStepSixHundred": exact_str(radius["original", 600]),
        "TstarReplicateUndeterminedStep": round_str(float(step), 0),
    }


def _validity(
    exp11: dict[str, Any] | None,
    exp11_sgd: dict[str, Any],
    exp11_adam: dict[str, Any],
    exp11_kfac_seam: dict[str, Any] | None = None,
) -> dict[str, str]:
    """Validity-radius macros along the K-FAC, SGD and Adam trajectories, plus D0.1's
    two-curvatures-disagree counts and D0.2's tolerance sensitivity, its undetermined cells (`_undetermined_macros`) and t* of the
    model without its damping term (`_undamped_validity`), all on the same three
    bundles; with the on-demand replicate of seed 42 (``exp11_kfac_seam``) also its
    cells against the original's (`_replicate_macros`).

    ``exp11`` is the on-demand K-FAC arm (`paper_data.config.OPTIONAL_EXPERIMENTS`);
    every macro here needs it -- it is the arm ``tab:validity`` itself reports, and
    the other two arms share its protocol and seeds -- so the whole group is left
    out, not raised, when it is absent, consistent with how `_stage_a` treats its
    own on-demand bundles. ``exp11_sgd``/``exp11_adam`` are not optional (a missing
    one fails earlier, at `paper_data.loader.load`), so they need no such guard.
    """
    if exp11 is None:
        return {}
    macros: dict[str, str] = {}
    arms = (exp11, exp11_sgd, exp11_adam)

    ok, total = _count_at_most(arms, 0.1, 200)
    macros["TstarCellsOk"] = round_str(float(ok), 0)
    macros["TstarCellsTotal"] = round_str(float(total), 0)
    ok_coarse, total_coarse = _count_at_most(arms, 0.25, 20)
    macros["TstarCellsOkCoarse"] = round_str(float(ok_coarse), 0)
    macros["TstarCellsTotalCoarse"] = round_str(float(total_coarse), 0)

    # Tighter thresholds use the same arms, steps and finite-cell denominator.
    # These are thresholds on t* itself, not the relative tolerance TstarTol.
    ok_twentieth, total_twentieth = _count_at_most(arms, 0.05, 200)
    if total_twentieth != total:
        raise ValueError(
            "TstarCellsOkTwentieth: denominator "
            f"{total_twentieth} at threshold 0.05 differs from TstarCellsTotal "
            f"{total} at threshold 0.1; the two reporting thresholds are no "
            "longer counting the same population of cells"
        )
    macros["TstarCellsOkTwentieth"] = round_str(float(ok_twentieth), 0)

    ok_hundredth, total_hundredth = _count_at_most(arms, 0.01, 200)
    if total_hundredth != total:
        raise ValueError(
            "TstarCellsOkHundredth: denominator "
            f"{total_hundredth} at threshold 0.01 differs from TstarCellsTotal "
            f"{total} at threshold 0.1; the two reporting thresholds are no "
            "longer counting the same population of cells"
        )
    macros["TstarCellsOkHundredth"] = round_str(float(ok_hundredth), 0)

    kfac_early = statistics.median(_tstar_at(exp11, _TSTAR_EARLY_STEPS))
    kfac_late = statistics.median(_tstar_at(exp11, _TSTAR_LATE_STEPS))
    macros["TstarMedianEarlyKfac"] = exact_str(kfac_early)
    macros["TstarMedianLateKfac"] = exact_str(kfac_late)
    macros["TstarDropKfac"] = round_str(kfac_early / kfac_late, 1)

    sgd_early = statistics.median(_tstar_at(exp11_sgd, _TSTAR_EARLY_STEPS))
    sgd_late = statistics.median(_tstar_at(exp11_sgd, _TSTAR_LATE_STEPS))
    macros["TstarDropSgd"] = round_str(sgd_early / sgd_late, 0)

    # Check equality of Adam's early and late median validity radii.
    adam_early = statistics.median(_tstar_at(exp11_adam, _TSTAR_EARLY_STEPS))
    adam_late = statistics.median(_tstar_at(exp11_adam, _TSTAR_LATE_STEPS))
    if adam_early != adam_late:
        raise ValueError(
            "TstarMedianAdam: Section 4.3 states Adam's median validity radius is "
            f"the same early and late, but the early window gives {adam_early!r} "
            f"and the late one {adam_late!r}; the sentence must change with it"
        )
    macros["TstarMedianAdam"] = exact_str(adam_early)

    pointwise: list[float] = []
    secant: list[float] = []
    per_seed_ratio: list[float] = []
    for payload in exp11["seeds"].values():
        probe = _probe_at(payload, 1500)
        pw = _curv_along_d0(probe)
        sc = _kappa_sec(probe)
        pointwise.append(pw)
        secant.append(sc)
        per_seed_ratio.append(pw / sc)
    curv_ratio = mean_std(pointwise)["mean"] / mean_std(secant)["mean"]
    macros["CurvRatioLast"] = round_str(curv_ratio, 1)
    macros["CurvRatioLastLo"] = round_str(min(per_seed_ratio), 1)
    macros["CurvRatioLastHi"] = round_str(max(per_seed_ratio), 1)

    # --- D0.1: the two curvatures disagree, and the direction depends on the
    # optimiser  -- every probe of the three arms and
    # three seeds, not just the last one CurvRatioLast above reports. The ||d0||^2
    # cancellation this ratio relies on is checked, not assumed
    # (`_curv_ratio_cancellation_holds`, exercised on every cell of the three arms
    # by `test_paper_data_numbers.py::test_curv_ratio_cancellation_of_norm_d0_squared`
    # -- not repeated here so this generator stays free of a test-only helper call).
    arm_bundles = {"Kfac": exp11, "Sgd": exp11_sgd, "Adam": exp11_adam}
    ratios_from_60: dict[str, list[float]] = {}
    cells_per_arm: int | None = None
    for arm_macro, bundle in arm_bundles.items():
        cells = _cell_curvatures(bundle, arm_macro)
        if cells_per_arm is None:
            cells_per_arm = len(cells)
        elif len(cells) != cells_per_arm:
            raise ValueError(
                f"{arm_macro} has {len(cells)} cells, expected {cells_per_arm}"
            )
        macros[f"SecantBelow{arm_macro}"] = round_str(
            float(sum(1 for _, pw, sc in cells if sc < pw)), 0
        )
        ratios_from_60[arm_macro] = [
            pw / sc for step, pw, sc in cells if step >= _CURV_RATIO_MIN_STEP
        ]
    assert cells_per_arm is not None
    macros["SecantCellsArm"] = round_str(float(cells_per_arm), 0)

    macros["CurvRatioMedianKfac"] = round_str(
        statistics.median(ratios_from_60["Kfac"]), 1
    )
    macros["CurvRatioMedianSgd"] = round_str(
        statistics.median(ratios_from_60["Sgd"]), 1
    )
    macros["CurvRatioMedianAdam"] = round_str(
        statistics.median(ratios_from_60["Adam"]), 1
    )

    span_pool = ratios_from_60["Kfac"] + ratios_from_60["Sgd"]
    macros["CurvRatioSpanLo"] = round_str(min(span_pool), 1)
    macros["CurvRatioSpanHi"] = round_str(max(span_pool), 1)
    macros["CurvRatioAdamLo"] = round_str(min(ratios_from_60["Adam"]), 1)
    macros["CurvRatioAdamHi"] = round_str(max(ratios_from_60["Adam"]), 1)

    # --- D0.2: t*'s sensitivity to the tolerance (Appendix B, the "below the grid"
    # convention already stated there in words) -- the same population as
    # TstarCellsOk: arm x seed x probe step at or after step 200, 27 cells.
    macros["TstarTol"] = round_str(_bundle_tolerance(arms), 1)

    t_stars_05 = _tstar_sweep(arms, 0.05, 200)
    _, median_05 = _tstar_ok_and_median(t_stars_05, 0.1)
    macros["TstarMedianTolFive"] = exact_str(median_05)

    t_stars_20 = _tstar_sweep(arms, 0.20, 200)
    ok_20, _ = _tstar_ok_and_median(t_stars_20, 0.1)
    macros["TstarCellsOkTolTwenty"] = round_str(float(ok_20), 0)

    t_stars_50 = _tstar_sweep(arms, 0.50, 200)
    ok_50, median_50 = _tstar_ok_and_median(t_stars_50, 0.1)
    macros["TstarCellsOkTolFifty"] = round_str(float(ok_50), 0)
    macros["TstarMedianTolFifty"] = exact_str(median_50)

    # Cells that fail at the first grid point on noise are undetermined, not below the
    # grid: counted apart at 0.05, refused at every other tolerance.
    macros.update(_undetermined_macros(arm_bundles, _bundle_tolerance(arms)))

    n_below_damping = n_lambda_total = 0
    for bundle in arms:
        lam = bundle["meta"]["damping"]
        for payload in bundle["seeds"].values():
            for probe in payload["probes"]:
                n_lambda_total += 1
                if float(probe["sharpness"]["lambda_min"]) < -lam:
                    n_below_damping += 1
    macros["LambdaMinCellsBelowDamping"] = round_str(float(n_below_damping), 0)
    macros["LambdaMinCellsTotal"] = round_str(float(n_lambda_total), 0)

    init_fracs = [_kink_frac(_probe_at(p, 0)) for p in exp11["seeds"].values()]
    late_fracs = [_kink_frac(_probe_at(p, 1500)) for p in exp11["seeds"].values()]
    macros["KinkShareInit"] = round_str(100 * mean_std(init_fracs)["mean"], 1)
    macros["KinkShareLate"] = round_str(100 * mean_std(late_fracs)["mean"], 1)

    # The replicate of seed 42 against the original run, on demand.
    if exp11_kfac_seam is not None:
        macros.update(_replicate_macros(exp11, exp11_kfac_seam))

    # t* of the model without its damping term, and the term's share.
    macros.update(_undamped_validity(exp11, exp11_sgd, exp11_adam))

    return macros


