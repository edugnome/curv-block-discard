"""Validate and report the fixed nine-state causal pilot from scalar records.

Author exports validate primary JSON and receipt identities. Public records retain
the scientific cohort and thresholds without author receipts.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
from typing import Any

from .config import DEFAULT_RESULTS_DIR
from .formatting import round_str

_SEEDS = (42, 43, 44)
_STEPS = (20, 60, 200)
_SCALE_GRID = (0.0, 0.03125, 0.0625, 0.125, 0.25, 0.5, 1.0)
_REFRESH = ("gradient_refresh", "curvature_refresh", "both_refresh")
_SUMMARY = Path("verification/v2-complete-cohort-summary.json")
_FILES = ("results.json", "status.json", "provenance.json", "thresholds.json")
_HEADER = "% Generated by paper_data.causal_pilot -- do not edit by hand."


def _same(actual: Any, expected: Any, context: str) -> None:
    if actual != expected:
        raise ValueError(f"{context}: {actual!r} != {expected!r}")


def _finite(value: Any) -> float:
    if (
        isinstance(value, bool)
        or not isinstance(value, (int, float))
        or not math.isfinite(value)
    ):
        raise ValueError(f"expected a finite number, got {value!r}")
    return float(value)


def _gain(candidate: dict[str, Any]) -> float:
    """Measured raw gain, never the loss of the accepted/applied fallback step."""
    gain = _finite(candidate["loss_d0"]) - _finite(candidate["loss"])
    _same(
        _finite(candidate["actual_gain"]), gain, "gain must equal L(d0) - L(candidate)"
    )
    return gain


def _candidate(candidate: dict[str, Any]) -> dict[str, Any]:
    _gain(candidate)
    return {key: candidate[key] for key in ("loss_d0", "loss", "actual_gain")}


def _cohort(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    expected = {(seed, step) for seed in _SEEDS for step in _STEPS}
    seen: set[tuple[int, int]] = set()
    for row in rows:
        identity = (row["seed"], row["step"])
        if identity not in expected:
            raise ValueError(f"unexpected primary state: {identity}")
        if identity in seen:
            raise ValueError(f"duplicate primary state: {identity}")
        seen.add(identity)
    if seen != expected:
        raise ValueError(f"missing primary states: {sorted(expected - seen)}")
    return sorted(rows, key=lambda row: (row["seed"], row["step"]))


def _validate_thresholds(thresholds: dict[str, Any]) -> None:
    """Validate the scientific gain and repeatability thresholds."""
    floor = _finite(thresholds["gain_floor"])
    error = _finite(
        thresholds.get("this_repeatability_error", thresholds["repeatability_error"])
    )
    if (
        floor <= 0
        or error < 0
        or floor < max(_finite(thresholds["tolerances"]["gain_floor"]), 10 * error)
    ):
        raise ValueError("invalid frozen gain/noise threshold")


def _fixed_thresholds(thresholds: dict[str, Any]) -> dict[str, Any]:
    """Select the frozen thresholds and calibration receipt for author exports."""
    _validate_thresholds(thresholds)
    return {
        key: thresholds[key]
        for key in (
            "schema",
            "tolerances",
            "gain_floor",
            "repeatability_error",
            "calibration_capture_sha256",
            "repeats",
        )
    }


def _validated_rows(causal_pilot: dict[str, Any]) -> list[dict[str, Any]]:
    _same(causal_pilot["schema"], 1, "canonical schema")
    if causal_pilot.get("format") == "curv-scientific-pilot-v1":
        thresholds = causal_pilot["thresholds"]
        _validate_thresholds(thresholds)
        for field in (
            "schema",
            "tolerances",
            "gain_floor",
            "repeatability_error",
            "repeats",
        ):
            thresholds[field]
    else:
        _fixed_thresholds(causal_pilot["thresholds"])
    rows = _cohort(causal_pilot["rows"])
    for row in rows:
        native = row["native"]
        candidates = native["candidates"]
        original = candidates["original"]
        for candidate in candidates.values():
            _gain(candidate)
            _same(candidate["loss_d0"], original["loss_d0"], "native baseline loss")
        for name in _REFRESH:
            _gain(candidates[name])
        scale = native["scale_control"]
        _same(
            [point["alpha"] for point in scale],
            list(_SCALE_GRID),
            "registered scale grid",
        )
        for i, point in enumerate(scale):
            _same(point["candidate"], f"scale_{i}", "scale candidate")
            _same(point["gain"], _gain(candidates[f"scale_{i}"]), "scale gain")
        _same(
            native["best_scale_gain"], max(p["gain"] for p in scale), "best scale gain"
        )
        _same(_gain(candidates["scale_0"]), 0.0, "zero-scale gain")
        _same(_gain(candidates["scale_6"]), _gain(original), "unit-scale gain")
        gates = original["original_gates"]
        _same(
            gates["loss"],
            original["loss"] < original["loss_d0"],
            "strict loss gate (no gain floor)",
        )
        rejected_by = next(
            (key for key in ("ratio", "model", "loss") if not gates[key]), None
        )
        _same(gates["rejected_by"], rejected_by, "raw rejection gate")
        _same(gates["accepted"], rejected_by is None, "raw acceptance")
        for key in ("predicted_endpoint_slope", "endpoint_slope"):
            _finite(native["comparison"][key])
        for name in ("relu", "pool"):
            _gain(row["interventions"][name])
    return rows


def _check_summary(row: dict[str, Any], reference: dict[str, Any]) -> None:
    """Reconcile presentation inputs with the selected scalar summary."""
    native = row["native"]
    original = native["candidates"]["original"]
    checks = {
        "capture_sha256": row["capture_sha256"],
        "original_gain": _gain(original),
        "original_gates": original["original_gates"],
        "best_scale_gain": native["best_scale_gain"],
    }
    for key, value in checks.items():
        _same(value, reference[key], f"verified summary {key}")
    for key in ("predicted_endpoint_slope", "endpoint_slope"):
        _same(
            native["comparison"][key],
            reference["comparison"][key],
            f"verified summary {key}",
        )
    for name in _REFRESH:
        gain = _gain(native["candidates"][name])
        _same(gain, reference["refresh"][name]["gain"], f"verified summary {name} gain")
        _same(
            gain - native["best_scale_gain"],
            reference["refresh"][name]["extra_vs_scale"],
            f"verified summary {name} scale gain",
        )
    for name in ("relu", "pool"):
        candidate = row["interventions"][name]
        values = {
            "gain": _gain(candidate),
            "surrogate_base_loss_shift": candidate["loss_d0"] - original["loss_d0"],
            "surrogate_candidate_loss_shift": candidate["loss"] - original["loss"],
        }
        for key, value in values.items():
            _same(
                value,
                reference["interventions"][name][key],
                f"verified summary {name} {key}",
            )


def reconstruct_summary(run_root: Path, primary_paths: list[Path]) -> dict[str, Any]:
    """Repackage explicitly selected scalar sidecars, not a new GPU verification.

    Callers stage the four primary JSON files and record their original locations.
    The unchanged exporter subsequently reconciles this summary against those files.
    No generic experiment summarizer or tensor input is used.
    """
    rows, inputs, sources = [], [], set()
    for relative in primary_paths:
        if (
            relative.parts[:2] != ("science-v2", "probes")
            or len(relative.parts) != 3
            or relative.name in (".", "..")
        ):
            raise ValueError(f"invalid primary path: {relative}")
        blobs = {name: (run_root / relative / name).read_bytes() for name in _FILES}
        data = json.loads(blobs["results.json"])
        provenance = json.loads(blobs["provenance.json"])
        sources.add(provenance["source"]["sha256"])
        native = data["native"]
        original = native["candidates"]["original"]
        best = native["best_scale_gain"]
        rows.append(
            {
                "seed": data["seed"],
                "step": data["step"],
                "path": relative.as_posix(),
                "capture_sha256": data["capture_sha256"],
                "original_gain": _gain(original),
                "original_gates": original["original_gates"],
                "best_scale_gain": best,
                "comparison": native["comparison"],
                "refresh": {
                    name: {
                        "gain": _gain(native["candidates"][name]),
                        "extra_vs_scale": _gain(native["candidates"][name]) - best,
                    }
                    for name in _REFRESH
                },
                "interventions": {
                    name: {
                        "gain": _gain(
                            data["interventions"][name]["measurements"]["candidates"][
                                "original"
                            ]
                        ),
                        "surrogate_base_loss_shift": data["interventions"][name][
                            "measurements"
                        ]["candidates"]["original"]["loss_d0"]
                        - original["loss_d0"],
                        "surrogate_candidate_loss_shift": data["interventions"][name][
                            "measurements"
                        ]["candidates"]["original"]["loss"]
                        - original["loss"],
                    }
                    for name in ("relu", "pool")
                },
            }
        )
        inputs.append(
            {
                "path": relative.as_posix(),
                "sha256": {
                    name: hashlib.sha256(blob).hexdigest()
                    for name, blob in blobs.items()
                },
            }
        )
    return {
        "complete_fixed_cohort": True,
        "n_primary": len(rows),
        "missing_primary": [],
        "source_sha256": sorted(sources),
        "rows": _cohort(rows),
        "packaging": {
            "kind": "scalar_reconstruction",
            "independent_gpu_verification": False,
            "inputs": inputs,
        },
    }


def export_cohort(run_root: Path) -> dict[str, Any]:
    """Build the compact canonical bundle; do not read or modify any.pt artifact."""
    summary_bytes = (run_root / _SUMMARY).read_bytes()
    summary = json.loads(summary_bytes)
    references = _cohort(summary["rows"])
    _same(summary["complete_fixed_cohort"], True, "complete fixed cohort")
    _same(summary["n_primary"], len(references), "summary primary count")
    _same(summary["missing_primary"], [], "summary missing states")
    rows, inputs = [], []
    fixed: dict[str, Any] | None = None
    source: str | None = None
    for reference in references:
        recorded_path = Path(reference["path"])
        if recorded_path.parts[-3:-1] != (
            "science-v2",
            "probes",
        ) or recorded_path.name in (".", ".."):
            raise ValueError(
                f"primary path is not in science-v2/probes: {recorded_path}"
            )
        relative = Path("science-v2/probes") / recorded_path.name
        blobs = {name: (run_root / relative / name).read_bytes() for name in _FILES}
        artifacts = {name: json.loads(blob) for name, blob in blobs.items()}
        data, status, provenance, thresholds = (artifacts[name] for name in _FILES)
        _same(status["status"], "complete", f"{relative} must be complete")
        _same(
            (data["seed"], data["step"]),
            (reference["seed"], reference["step"]),
            "primary identity",
        )
        if not data["tests"] or any(
            value != "complete" for value in data["tests"].values()
        ):
            raise ValueError(f"{relative}: tests are not complete")
        for check in ("original_model_replay", "production_acceptance_check"):
            _same(data[check]["passed"], True, check)
        capture = provenance["capture_manifest"]
        _same(
            (capture["seed"], capture["step"]),
            (data["seed"], data["step"]),
            "capture identity",
        )
        _same(capture["sha256"], data["capture_sha256"], "capture checksum")
        this_source = provenance["source"]["sha256"]
        _same(this_source, capture["provenance"]["source"]["sha256"], "capture source")
        _same(summary["source_sha256"], [this_source], "summary source")
        if source is not None:
            _same(this_source, source, "mixed source snapshots")
        source = this_source
        _same(data["thresholds"], thresholds, "embedded/sidecar thresholds")
        this_fixed = _fixed_thresholds(thresholds)
        if fixed is not None:
            _same(this_fixed, fixed, "mixed frozen thresholds")
        fixed = this_fixed
        native = data["native"]
        # Check even the matched-norm candidates, although they are not exported.
        for candidate in native["candidates"].values():
            _gain(candidate)
        names = ("original", *_REFRESH, *(f"scale_{i}" for i in range(7)))
        candidates = {name: _candidate(native["candidates"][name]) for name in names}
        candidates["original"]["original_gates"] = native["candidates"]["original"][
            "original_gates"
        ]
        _same(
            native["comparison"]["actual_gain"],
            _gain(candidates["original"]),
            "native comparison gain",
        )
        row = {
            "seed": data["seed"],
            "step": data["step"],
            "capture_sha256": data["capture_sha256"],
            "native": {
                "candidates": candidates,
                "scale_control": native["scale_control"],
                "best_scale_gain": native["best_scale_gain"],
                "comparison": {
                    key: native["comparison"][key]
                    for key in ("predicted_endpoint_slope", "endpoint_slope")
                },
            },
            "interventions": {
                name: _candidate(
                    data["interventions"][name]["measurements"]["candidates"][
                        "original"
                    ]
                )
                for name in ("relu", "pool")
            },
        }
        rows.append(row)
        inputs.append(
            {
                "path": relative.as_posix(),
                "sha256": {
                    name: hashlib.sha256(blob).hexdigest()
                    for name, blob in blobs.items()
                },
            }
        )
    bundle = {
        "schema": 1,
        "thresholds": fixed,
        "provenance": {
            "run_root": run_root.name,
            "source_sha256": source,
            "summary": {
                "path": _SUMMARY.as_posix(),
                "sha256": hashlib.sha256(summary_bytes).hexdigest(),
                **(
                    {
                        key: summary["packaging"][key]
                        for key in ("kind", "independent_gpu_verification")
                    }
                    if "packaging" in summary
                    else {}
                ),
            },
            "inputs": inputs,
        },
        "rows": rows,
    }
    _validated_rows(bundle)
    for row, reference in zip(rows, references, strict=True):
        _check_summary(row, reference)
    return bundle


def _rank(gain: float, floor: float) -> int:
    """Strict finite-step loss preference; the closed [-floor, floor] band is a tie."""
    return 0 if abs(gain) <= floor else (1 if gain > 0 else -1)


def causal_pilot_numbers(causal_pilot: dict[str, Any]) -> str:
    """Counts from raw gains, not acceptance or a surrogate/native mixed loss."""
    rows = _validated_rows(causal_pilot)
    floor = causal_pilot["thresholds"]["gain_floor"]
    counts = {
        "CausalPilotStates": len(rows),
        "CausalPilotSeeds": len({row["seed"] for row in rows}),
        "CausalPilotRawLossRejects": 0,
        "CausalPilotGradientScaleWins": 0,
        "CausalPilotCurvatureScaleWins": 0,
        "CausalPilotBothScaleWins": 0,
        "CausalPilotSlopeSignFlips": 0,
        "CausalPilotReluFlips": 0,
        "CausalPilotPoolFlips": 0,
        "CausalPilotReluBothLossesRiseFlips": 0,
    }
    for row in rows:
        native = row["native"]
        original = native["candidates"]["original"]
        counts["CausalPilotRawLossRejects"] += (
            original["original_gates"]["rejected_by"] == "loss"
        )
        for name, macro in zip(
            _REFRESH, ("Gradient", "Curvature", "Both"), strict=True
        ):
            extra = _gain(native["candidates"][name]) - native["best_scale_gain"]
            counts[f"CausalPilot{macro}ScaleWins"] += extra > floor
        comparison = native["comparison"]
        counts["CausalPilotSlopeSignFlips"] += (
            comparison["predicted_endpoint_slope"] * comparison["endpoint_slope"] < 0
        )
        for name, macro in (("relu", "Relu"), ("pool", "Pool")):
            candidate = row["interventions"][name]
            flip = _rank(_gain(original), floor) * _rank(_gain(candidate), floor) == -1
            counts[f"CausalPilot{macro}Flips"] += flip
            if name == "relu" and flip:
                counts["CausalPilotReluBothLossesRiseFlips"] += (
                    candidate["loss_d0"] > original["loss_d0"]
                    and candidate["loss"] > original["loss"]
                )
    lines = [_HEADER]
    lines.extend(
        rf"\newcommand{{\{name}}}{{{value}}}" for name, value in counts.items()
    )
    lines.append(rf"\newcommand{{\CausalPilotGainFloor}}{{{round_str(floor, 4)}}}")
    return "\n".join(lines)


def causal_pilot_table(causal_pilot: dict[str, Any]) -> str:
    """All nine states, with ReLU surrogate losses explicitly relative to native."""
    rows = _validated_rows(causal_pilot)
    lines = [
        _HEADER,
        r"\begin{table}[htbp]",
        r"\centering",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{rrrrrrr}",
        r"\toprule",
        r"Seed & Step & Native gain & Grad. extra & ReLU gain & $\Delta L_0$ & $\Delta L_1$ \\",
        r"\midrule",
    ]
    for row in rows:
        native = row["native"]
        original = native["candidates"]["original"]
        relu = row["interventions"]["relu"]
        values = (
            _gain(original),
            _gain(native["candidates"]["gradient_refresh"]) - native["best_scale_gain"],
            _gain(relu),
            relu["loss_d0"] - original["loss_d0"],
            relu["loss"] - original["loss"],
        )
        cells = [
            str(row["seed"]),
            str(row["step"]),
            *(f"${round_str(value, 4)}$" for value in values),
        ]
        lines.append(" & ".join(cells) + r" \\")
    lines.extend(
        [
            r"\bottomrule",
            r"\end{tabular}",
            r"\caption{Frozen-state one-step refresh and surrogate comparisons; every gain is $L(d_0)-L(d)$ within the same loss function. Native gain uses the raw correction, not the accepted fallback. Grad. extra is the gradient-refresh native gain minus the best gain on the registered discrete scale grid. ReLU gain uses the fixed-ReLU surrogate. The last two columns are surrogate minus native losses at the baseline ($\Delta L_0$) and raw corrected ($\Delta L_1$) steps; positive values mean worse losses, not a native-loss improvement.}",
            r"\label{tab:causal-pilot}",
            r"\end{table}",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-root", type=Path, required=True)
    parser.add_argument(
        "--output", type=Path, default=DEFAULT_RESULTS_DIR / "causal_pilot/results.json"
    )
    args = parser.parse_args()
    bundle = export_cohort(args.run_root)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(bundle, indent=2, allow_nan=False) + "\n", encoding="utf-8"
    )


if __name__ == "__main__":
    main()
